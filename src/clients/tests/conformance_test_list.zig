const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");
const Arena = conformance.Arena;
const Printer = conformance.Printer;
const Words = conformance.Words;

const stdx = @import("stdx");

const clients_directory = "src/clients/";
const languages_count = 6;
const cases_max = 32;
// NOTE: We still have some long lines in the generators, so we want a limit well above that.
const generated_line_length_max = 256;

const Language = struct {
    client: []const u8,
    test_file: []const u8,
};

const Lines = struct {
    sync: ?u32 = null,
    async: ?u32 = null,
};

// Dumps a list of suites and tests in Markdown format, with links to the generated tests.
// Arguments: the path of each language's generated test file, relative to the repository root.
pub fn main(init: std.process.Init) !void {
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);

    var args = init.minimal.args.iterate();
    _ = args.skip();
    var languages: [languages_count]Language = undefined;
    for (0..languages_count) |index| {
        const path = args.next().?;
        const client, _ = stdx.cut(stdx.cut_prefix(path, clients_directory).?, "/").?;
        languages[index] = .{ .client = client, .test_file = path };
    }
    assert(args.next() == null);

    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const writer = &stdout.interface;
    var printer = Printer.init(&arena, writer, .{ .indent_width = 4 });
    try printer.print(
        \\<!-- This file is generated by [{0s}]({0s}). -->
        \\# Conformance Test Suite
        \\
    , .{"/src/clients/tests/conformance_test_list.zig"});
    for (conformance.sources) |source| {
        const suite_memory = printer.arena.mark();
        defer printer.arena.release(suite_memory);

        const suite = try conformance.parse(printer.arena.allocator(), source);
        assert(suite.cases.len <= cases_max);
        var key_buffers: [cases_max][generated_line_length_max]u8 = undefined;
        var keys: [cases_max][]const u8 = undefined;
        for (suite.cases, 0..) |case, case_index| {
            keys[case_index] = normalize(&key_buffers[case_index], &.{
                suite.name,
                case.description,
            });
        }
        var lines: [languages_count][cases_max]Lines = @splat(@splat(.{}));
        for (languages, 0..) |language, language_index| {
            try scan(
                init.io,
                language.test_file,
                keys[0..suite.cases.len],
                &lines[language_index],
            );
        }

        try printer.write_empty_line();
        try printer.print_indented("- {s}", .{suite.name});
        printer.indent();
        for (suite.cases, 0..) |case, case_index| {
            try printer.write_indent();
            try printer.print("- {s}", .{case.description});
            if (case.requirement) |requirement| {
                try printer.print(" ({s})", .{@tagName(requirement)});
            }
            try printer.write("\n");
            printer.indent();
            for (languages, 0..) |language, language_index| {
                const case_lines = lines[language_index][case_index];
                if (case_lines.sync) |line| {
                    try write_link(&printer, language, line, .{});
                } else {
                    if (case.requirement == null) {
                        std.debug.panic("{s}: no test for {s}/{s}", .{
                            language.test_file, suite.name, case.description,
                        });
                    }
                    try printer.print_indented("- {s} (omitted)", .{language.client});
                }
                if (case_lines.async) |line| {
                    assert(case_lines.sync != null);
                    try write_link(&printer, language, line, .{ .async = true });
                }
            }
            printer.dedent();
        }
        printer.dedent();
    }
    try writer.flush();
}

fn write_link(
    printer: *Printer,
    language: Language,
    line: u32,
    options: struct { async: bool = false },
) !void {
    try printer.print_indented("- [{s}{s}](../{s}#L{d})", .{
        language.client,
        if (options.async) " async" else "",
        stdx.cut_prefix(language.test_file, clients_directory).?,
        line,
    });
}

fn scan(
    io: std.Io,
    test_file: []const u8,
    keys: []const []const u8,
    lines: *[cases_max]Lines,
) !void {
    const file = try std.Io.Dir.cwd().openFile(io, test_file, .{});
    defer file.close(io);

    var line_buffer: [generated_line_length_max + 1]u8 = undefined;
    var file_reader = file.reader(io, &line_buffer);
    var identifier_buffer: [generated_line_length_max]u8 = undefined;
    var line_number: u32 = 1;
    while (try file_reader.interface.takeDelimiter('\n')) |line| : (line_number += 1) {
        var identifiers = Words{ .input = line, .include_underscore = true };
        while (identifiers.next()) |identifier| {
            const normalized = normalize(&identifier_buffer, &.{identifier});
            const name = stdx.cut_prefix(normalized, "test") orelse normalized;
            const name_without_async = stdx.cut_suffix(name, "async");
            for (keys, 0..) |key, case_index| {
                if (std.mem.eql(u8, name, key)) {
                    assert(lines[case_index].sync == null);
                    lines[case_index].sync = line_number;
                } else if (name_without_async != null and
                    std.mem.eql(u8, name_without_async.?, key))
                {
                    assert(lines[case_index].async == null);
                    lines[case_index].async = line_number;
                }
            }
        }
    }
}

fn normalize(buffer: []u8, inputs: []const []const u8) []const u8 {
    var length: usize = 0;
    for (inputs) |input| {
        for (input) |char| {
            if (!std.ascii.isAlphanumeric(char)) continue;
            buffer[length] = std.ascii.toLower(char);
            length += 1;
        }
    }
    return buffer[0..length];
}
