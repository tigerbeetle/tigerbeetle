const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Arena = conformance.Arena;
const Printer = conformance.Printer;

pub fn main(init: std.process.Init) !void {
    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const stdout_writer = &stdout.interface;
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);
    var printer = Printer.init(&arena, stdout_writer, .{
        .indent_width = 2,
    });

    try emit(&printer);
    try stdout_writer.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        // Amounts are `bigint`s: arbitrary precision, but integral only.
        .requires_unbounded_integers => true,
        .requires_fractional_amounts => false,
    };
}

fn emit(printer: *Printer) !void {
    try printer.write(
        \\///////////////////////////////////////////////////////////
        \\// This file was auto-generated by node_conformance.zig  //
        \\//               Do not manually modify.                 //
        \\///////////////////////////////////////////////////////////
        \\
        \\import assert, { AssertionError } from 'assert'
        \\import {
        \\  Account,
        \\  AccountFilter,
        \\  AccountFilterFlags,
        \\  AccountFlags,
        \\  Client,
        \\  createClient,
        \\  CreateAccountStatus,
        \\  CreateTransferStatus,
        \\  ErrorCodes,
        \\  id,
        \\  QueryFilter,
        \\  QueryFilterFlags,
        \\  RequestError,
        \\  Transfer,
        \\  TransferFlags,
        \\} from '.'
        \\
        \\const REPLICA_ADDRESSES = [process.env.TB_ADDRESS || '3000'];
        \\
        \\// Every field is required, so cases spread these and override only what they set.
        \\const account_default: Account = {
        \\  id: 0n,
        \\  debits_pending: 0n,
        \\  debits_posted: 0n,
        \\  credits_pending: 0n,
        \\  credits_posted: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  reserved: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  flags: 0,
        \\  timestamp: 0n,
        \\}
        \\
        \\const transfer_default: Transfer = {
        \\  id: 0n,
        \\  debit_account_id: 0n,
        \\  credit_account_id: 0n,
        \\  amount: 0n,
        \\  pending_id: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  timeout: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  flags: 0,
        \\  timestamp: 0n,
        \\}
        \\
        \\const account_filter_default: AccountFilter = {
        \\  account_id: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  code: 0,
        \\  timestamp_min: 0n,
        \\  timestamp_max: 0n,
        \\  limit: 0,
        \\  flags: 0,
        \\}
        \\
        \\const query_filter_default: QueryFilter = {
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  timestamp_min: 0n,
        \\  timestamp_max: 0n,
        \\  limit: 0,
        \\  flags: 0,
        \\}
        \\
        \\async function sleep_ms(ms: number): Promise<void> {
        \\  await new Promise(resolve => setTimeout(resolve, ms))
        \\}
        \\
        \\const tests: Array<{ name: string, fn: (client: Client) => Promise<void> }> = []
        \\function test(name: string, fn: (client: Client) => Promise<void>) {
        \\  tests.push({ name, fn })
        \\}
        \\
    );
    for (conformance.sources) |source| {
        defer printer.arena.reset();

        const suite = try conformance.parse(printer.arena.allocator(), source);
        try printer.write_empty_line();
        try printer.print_indented("// Suite: {s}", .{suite.name});
        for (suite.cases) |case| {
            printer.arena.mark();
            defer printer.arena.restore();

            try printer.write_empty_line();
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    try printer.write_omission(case);
                    continue;
                }
            }
            try printer.write_indented("test(");
            printer.indent();
            try printer.print_indented("'{s}_{s}',", .{
                suite.name,
                try printer.to_case_alloc(.snake_case, case.description),
            });
            try printer.write_indented("async (client) => {");
            printer.indent();
            for (case.steps) |step| try emit_step(printer, step);
            printer.dedent();
            try printer.write_indented("},");
            printer.dedent();
            try printer.write_indented(")");
        }
    }
    try printer.write(
        \\
        \\async function main () {
        \\  const start = new Date().getTime()
        \\  for (let i = 0; i < tests.length; i++) {
        \\    const client = createClient({
        \\      cluster_id: 0n,
        \\      replica_addresses: REPLICA_ADDRESSES,
        \\    })
        \\    try {
        \\      await tests[i].fn(client).then(() => {
        \\        console.log(tests[i].name + ": PASSED")
        \\      }).catch(error => {
        \\        console.log(tests[i].name + ": FAILED")
        \\        throw error
        \\      })
        \\    } finally {
        \\      client.destroy()
        \\    }
        \\  }
        \\  const end = new Date().getTime()
        \\  console.log('Time taken (s):', (end - start)/1000)
        \\}
        \\
        \\main().catch((error: AssertionError) => {
        \\  console.log('operator:', error.operator)
        \\  console.log('stack:', error.stack)
        \\  process.exit(-1);
        \\})
        \\
    );
}

fn emit_step(printer: *Printer, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(printer, binding),
        .call => |call| try emit_call(printer, call, .{}),
        .assertion => |assertion| try emit_assertion(printer, assertion),
        .directive => |directive| try emit_directive(printer, directive),
        .create_client => |arguments| try emit_create_client(printer, arguments, .success),
    }
}

fn emit_create_client(
    printer: *Printer,
    arguments: ast.ClientInitArgs,
    outcome: union(enum) { success, failure: ?ast.ClientError },
) !void {
    const cluster_id = try render_bigint(printer, arguments.cluster_id);
    const replica_addresses = switch (arguments.replica_addresses) {
        .server => "REPLICA_ADDRESSES",
        .literal => |text| try printer.string_alloc("['{s}']", .{text}),
    };
    switch (outcome) {
        .success => try printer.print_indented(
            "createClient({{ cluster_id: {s}, replica_addresses: {s} }}).destroy()",
            .{ cluster_id, replica_addresses },
        ),
        .failure => |client_error| {
            try printer.write_indented("assert.throws(");
            printer.indent();
            try printer.write_indented("() => createClient({");
            printer.indent();
            try printer.print_indented("cluster_id: {s},", .{cluster_id});
            try printer.print_indented("replica_addresses: {s},", .{replica_addresses});
            printer.dedent();
            try printer.write_indented("}),");
            if (client_error) |expected| {
                const message = switch (expected) {
                    .address_invalid => "Invalid replica address.",
                    .address_limit_exceeded => "Too many replica addresses.",
                    .cluster_id_invalid => "cluster_id must fit in 128 bits",
                    .too_much_data, .client_closed => unreachable,
                };
                try printer.print_indented("{{ message: '{s}' }},", .{message});
            }
            printer.dedent();
            try printer.write_indented(")");
        },
    }
}

fn emit_directive(printer: *Printer, directive: ast.HarnessDirective) !void {
    switch (directive) {
        .sleep_ms => |ms| try printer.print_indented("await sleep_ms({d})", .{ms}),
        .concurrently => |concurrently| {
            try printer.print_indented(
                "const operations = Array.from({{ length: {d} }}, () =>",
                .{concurrently.n},
            );
            printer.indent();
            try emit_call(printer, concurrently.call, .{ .awaited = false });
            printer.dedent();
            try printer.write_indented(")");
            try printer.write_indented("await Promise.all(operations)");
        },
    }
}

fn emit_binding(printer: *Printer, binding: ast.Binding) !void {
    switch (binding.value) {
        .generate_id, .index, .field_access => {
            const rendered = try render_expression(printer, binding.value);
            try printer.print_indented("const {s} = {s}", .{ binding.name, rendered });
        },
        .generate_ids => |count| {
            try printer.print_indented("const {s}: bigint[] = []", .{binding.name});
            try printer.print_indented("for (let index = 0; index < {d}; index++) {{", .{count});
            printer.indent();
            try printer.print_indented("if (index % {d} === 0) {{", .{
                ast.ids_between_sleeps,
            });
            printer.indent();
            try printer.write_indented("await sleep_ms(1)");
            printer.dedent();
            try printer.write_indented("}");
            try printer.print_indented("{s}.push(id())", .{binding.name});
            printer.dedent();
            try printer.write_indented("}");
        },
        .call => |call| {
            const prefix = try printer.string_alloc("const {s} = ", .{binding.name});
            try emit_call(printer, call, .{ .prefix = prefix });
        },
        .integer,
        .boolean,
        .enum_literal,
        .record,
        .reference,
        .increment,
        .decrement,
        => unreachable,
    }
}

fn emit_call(
    printer: *Printer,
    call: ast.Call,
    options: struct {
        prefix: []const u8 = "",
        awaited: bool = true,
    },
) !void {
    const awaited = if (options.awaited) "await " else "";
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try printer.write_indented("client.destroy()");
        },
        .create_accounts, .create_transfers => {
            if (call.arguments.len == 0) {
                try printer.print_indented("{s}{s}client.{s}([])", .{
                    options.prefix, awaited, try method_name(printer, call.name),
                });
                return;
            }
            try printer.print_indented("{s}{s}client.{s}([", .{
                options.prefix, awaited, try method_name(printer, call.name),
            });
            printer.indent();
            for (call.arguments) |argument| {
                try emit_record(printer, argument.record, .{ .suffix = "," });
            }
            printer.dedent();
            try printer.write_indented("])");
        },
        .lookup_accounts, .lookup_transfers => {
            try printer.write_indent();
            try printer.print("{s}{s}client.{s}([", .{
                options.prefix, awaited, try method_name(printer, call.name),
            });
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try printer.write(", ");
                try printer.write(try render_id(printer, argument));
            }
            try printer.write("])\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const prefix = try printer.string_alloc("{s}{s}client.{s}(", .{
                options.prefix, awaited, try method_name(printer, call.name),
            });
            try emit_record(printer, call.arguments[0].record, .{
                .prefix = prefix,
                .suffix = ")",
            });
        },
    }
}

fn emit_record(
    printer: *Printer,
    record: ast.Record,
    options: struct {
        prefix: []const u8 = "",
        suffix: []const u8 = "",
    },
) !void {
    try printer.print_indented("{s}{{", .{options.prefix});
    printer.indent();
    try printer.print_indented("...{s},", .{record_default(record.type)});
    for (record.fields) |field| {
        const value = try render_typed_value(printer, field.field, field.value);
        try printer.print_indented("{s}: {s},", .{ field.field.name, value });
    }
    printer.dedent();
    try printer.print_indented("}}{s}", .{options.suffix});
}

fn emit_assertion(
    printer: *Printer,
    assertion: ast.Assertion,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try printer.print_indented("assert.strictEqual({s}.length, {d})", .{
                equal.actual, equal.expected.len,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_typed_value(printer, field.field, field.value);
                    try printer.print_indented("assert.strictEqual({s}[{d}].{s}, {s})", .{
                        equal.actual, index, field.field.name, value,
                    });
                }
            }
        },
        .empty => |actual| {
            try printer.print_indented("assert.strictEqual({s}.length, 0)", .{actual});
        },
        .id_ascending => |ids| {
            try printer.print_indented("for (let i = 1; i < {s}.length; i++) {{", .{ids});
            printer.indent();
            try printer.print_indented("assert.ok({s}[i - 1] < {s}[i])", .{ ids, ids });
            printer.dedent();
            try printer.write_indented("}");
        },
        .equal_field => |comparison| {
            const value = switch (comparison.expected) {
                .expression => |expression| try render_typed_value(
                    printer,
                    comparison.actual.field,
                    expression,
                ),
                .field_reference => |field| try render_field_access(printer, field),
            };
            try printer.print_indented("assert.strictEqual({s}.{s}, {s})", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .greater_than => |comparison| {
            const value = try render_typed_value(
                printer,
                comparison.actual.field,
                comparison.expected.expression,
            );
            try printer.print_indented("assert.ok({s}.{s} > {s})", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .fail => |failure| switch (failure.action) {
            .call => |call| {
                try printer.write_indented("await assert.rejects(async (): Promise<void> => {");
                printer.indent();
                try emit_call(printer, call, .{});
                printer.dedent();
                if (failure.client_error) |client_error| {
                    try printer.write_indented("}, (error: unknown): boolean => {");
                    printer.indent();
                    try printer.write_indented("assert.ok(error instanceof RequestError)");
                    try printer.print_indented("assert.strictEqual(error.code, ErrorCodes.{s})", .{
                        node_error_code(client_error),
                    });
                    try printer.write_indented("return true");
                    printer.dedent();
                    try printer.write_indented("})");
                } else {
                    try printer.write_indented("})");
                }
            },
            .create_client => |arguments| {
                try emit_create_client(printer, arguments, .{ .failure = failure.client_error });
            },
        },
    }
}

fn node_error_code(client_error: ast.ClientError) []const u8 {
    return switch (client_error) {
        .too_much_data => "ERR_TOO_MUCH_DATA",
        .client_closed => "ERR_CLIENT_CLOSED",
        .address_invalid, .address_limit_exceeded, .cluster_id_invalid => unreachable,
    };
}

fn method_name(printer: *Printer, name: ast.Call.Name) ![]const u8 {
    return printer.to_case_alloc(.camelCase, @tagName(name));
}

fn record_default(record_type: ast.Record.Type) []const u8 {
    return switch (record_type) {
        .Account => "account_default",
        .Transfer => "transfer_default",
        .AccountFilter => "account_filter_default",
        .QueryFilter => "query_filter_default",
        .AccountBalance,
        .AccountFilterFlags,
        .AccountFlags,
        .CreateAccountResult,
        .CreateTransferResult,
        .QueryFilterFlags,
        .TransferFlags,
        => unreachable,
    };
}

fn render_expression(
    printer: *Printer,
    expression: ast.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .call, .generate_ids, .record => unreachable,
        .integer => |text| return text,
        .boolean => |value| return if (value) "true" else "false",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return printer.string_alloc("{s}[{d}]", .{
                index.reference,
                index.index,
            });
        },
        .field_access => |access| return render_field_access(printer, access),
        .increment => |arithmetic| return render_arithmetic(printer, arithmetic, "+"),
        .decrement => |arithmetic| return render_arithmetic(printer, arithmetic, "-"),
    }
}

fn render_id(printer: *Printer, expression: ast.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .reference => |name| return name,
        .integer => |text| return render_bigint(printer, text),
        else => unreachable,
    }
}

fn render_flags(printer: *Printer, record: ast.Record) ![]const u8 {
    if (record.fields.len == 0) {
        return printer.string_alloc("{s}.none", .{@tagName(record.type)});
    }
    var text = std.Io.Writer.Allocating.init(printer.arena.allocator());
    for (record.fields, 0..) |field, index| {
        assert(field.value == .boolean and field.value.boolean);
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.print("{s}.{s}", .{ @tagName(record.type), field.field.name });
    }
    return text.written();
}

fn render_field_access(
    printer: *Printer,
    reference: ast.FieldReference,
) ![]const u8 {
    return printer.string_alloc("{s}.{s}", .{
        reference.reference,
        reference.field.name,
    });
}

// `arithmetic.reference` must hold a `bigint`, because the result is a
// `bigint` expression.
fn render_arithmetic(
    printer: *Printer,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
) ![]const u8 {
    return printer.string_alloc("{s} {s} {d}n", .{
        arithmetic.reference,
        operator,
        arithmetic.by,
    });
}

fn render_typed_value(
    printer: *Printer,
    field: ast.Field,
    value: ast.Expression,
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            return printer.string_alloc("{s}.{s}", .{
                field.type.enum_name,
                literal,
            });
        },
        .record => |record| {
            assert(ast.Record.is_flags(record.type));
            return render_flags(printer, record);
        },
        .integer => |text| {
            if (field.type.int >= 64) return render_bigint(printer, text);
            return text;
        },
        .generate_id,
        .boolean,
        .reference,
        .index,
        .field_access,
        .increment,
        .decrement,
        => {
            return render_expression(printer, value);
        },
        .call, .generate_ids => unreachable,
    }
}

fn render_bigint(printer: *Printer, text: []const u8) ![]const u8 {
    return printer.string_alloc("{s}n", .{text});
}
