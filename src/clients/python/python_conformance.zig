const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Formatter = conformance.Formatter;

pub fn main(init: std.process.Init) !void {
    const formatter = Formatter.init(conformance.allocator(), .{
        .indent_width = 4,
        .start_level = 0,
        .comment_marker = "#",
    });

    const tests = try conformance.parse(formatter.arena);

    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    try emit(formatter, &stdout.interface, tests);
    try stdout.interface.flush();
}

// TODO: This produces failing tests until the following PR gets merged:
// https://github.com/tigerbeetle/tigerbeetle/pull/3917
fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => true,
        .requires_fractional_amounts => true,
    };
}

fn emit(formatter: Formatter, writer: *std.Io.Writer, tests: ast.ConformanceTests) !void {
    try writer.writeAll(
        \\############################################################
        \\## This file was auto-generated by python_conformance.zig ##
        \\##               Do not manually modify.                  ##
        \\############################################################
        \\
        \\import os
        \\import sys
        \\import threading
        \\import time
        \\
        \\import pytest
        \\
        \\import tigerbeetle as tb
        \\
        \\replica_addresses = os.getenv("TB_ADDRESS")
        \\if not replica_addresses:
        \\    print("error: missing TB_ADDRESS environment variable")
        \\    sys.exit(1)
        \\
        \\
        \\@pytest.fixture
        \\def client():
        \\    client = tb.ClientSync(cluster_id=0, replica_addresses=replica_addresses)
        \\    yield client
        \\    # Cases that close the client leave nothing for the teardown to close.
        \\    if client._client_key in tb.ClientSync._clients:
        \\        client.close()
        \\
    );
    for (tests.suites) |suite| {
        try writer.writeAll("\n");
        try writer.print("# Suite: {s}\n", .{suite.name});
        for (suite.cases) |case| {
            try writer.writeAll("\n");
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    const text = try formatter.generate_omission(case);
                    try writer.writeAll(text);
                    continue;
                }
            }
            try writer.print("def test_{s}_{s}(client):\n", .{
                suite.name,
                try formatter.to_case(.snake_case, case.description),
            });
            for (case.steps) |step| try emit_step(formatter, writer, step);
        }
    }
}

fn emit_step(formatter: Formatter, writer: *std.Io.Writer, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(formatter, writer, binding),
        .call => |call| try emit_call(formatter, writer, call, .{}),
        .assertion => |assertion| try emit_assertion(formatter, writer, assertion),
    }
}

fn emit_binding(formatter: Formatter, writer: *std.Io.Writer, binding: ast.Binding) !void {
    switch (binding.value) {
        .generate_id, .generate_ids, .index => {
            const rendered = try render_expression(formatter, binding.value);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("{s} = {s}\n", .{ binding.name, rendered });
        },
        .record => |record| switch (record.type) {
            .U128 => {
                const rendered = try render_expression(formatter, binding.value);
                try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                try writer.print("{s} = {s}\n", .{ binding.name, rendered });
            },
            .Account, .Transfer => {
                const prefix = try std.fmt.allocPrint(formatter.arena, "{s} = ", .{binding.name});
                try emit_record(formatter, writer, record, .{
                    .indent_level = formatter.statement_level,
                    .prefix = prefix,
                });
            },
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| {
            const prefix = try std.fmt.allocPrint(formatter.arena, "{s} = ", .{binding.name});
            try emit_call(formatter, writer, call, .{ .prefix = prefix });
        },
        .integer, .boolean, .enum_literal, .reference => unreachable,
    }
}

fn emit_call(
    formatter: Formatter,
    writer: *std.Io.Writer,
    call: ast.Call,
    options: struct {
        prefix: []const u8 = "",
    },
) !void {
    if (call.concurrency > 1) {
        assert(options.prefix.len == 0);
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("def operation():\n");
        try emit_invocation(formatter, writer, call, .{
            .indent_level = formatter.statement_level + 1,
        });
        try writer.writeAll("\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("threads = [threading.Thread(target=operation) for _ in range({d})]\n", .{
            call.concurrency,
        });
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("for thread in threads:\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("thread.start()\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("for thread in threads:\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("thread.join()\n");
    } else {
        try emit_invocation(formatter, writer, call, .{
            .indent_level = formatter.statement_level,
            .prefix = options.prefix,
        });
    }
}

fn emit_invocation(
    formatter: Formatter,
    writer: *std.Io.Writer,
    call: ast.Call,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
    },
) !void {
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("client.close()\n");
        },
        .sleep_ms => {
            assert(options.prefix.len == 0);
            assert(call.arguments.len == 1);
            const ms = try render_expression(formatter, call.arguments[0]);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("time.sleep({s} / 1000)\n", .{ms});
        },
        .create_accounts, .create_transfers => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            if (call.arguments.len == 0) {
                try writer.print("{s}client.{s}([])\n", .{ options.prefix, @tagName(call.name) });
                return;
            }
            try writer.print("{s}client.{s}(\n", .{ options.prefix, @tagName(call.name) });
            try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
            try writer.writeAll("[\n");
            for (call.arguments) |argument| switch (argument) {
                .record => |record| try emit_record(formatter, writer, record, .{
                    .indent_level = options.indent_level + 2,
                    .suffix = ",",
                }),
                .reference => |reference| {
                    try formatter.write_indent(writer, .{ .level = options.indent_level + 2 });
                    try writer.print("{s},\n", .{reference});
                },
                else => unreachable,
            };
            try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
            try writer.writeAll("]\n");
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll(")\n");
        },
        .lookup_accounts, .lookup_transfers => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("{s}client.{s}([", .{ options.prefix, @tagName(call.name) });
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try writer.writeAll(", ");
                try writer.writeAll(try render_expression(formatter, argument));
            }
            try writer.writeAll("])\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("{s}client.{s}(\n", .{ options.prefix, @tagName(call.name) });
            try emit_record(formatter, writer, call.arguments[0].record, .{
                .indent_level = options.indent_level + 1,
            });
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll(")\n");
        },
    }
}

fn emit_record(
    formatter: Formatter,
    writer: *std.Io.Writer,
    record: ast.Record,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        suffix: []const u8 = "",
    },
) !void {
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("{s}tb.{s}(\n", .{ options.prefix, @tagName(record.type) });
    switch (record.type) {
        .AccountFilter, .QueryFilter => {
            for (filter_fields(record.type)) |field_name| {
                const value = if (find_field(record, field_name)) |field|
                    try render_typed_value(formatter, field.field, field.value)
                else if (std.mem.eql(u8, field_name, "flags"))
                    try std.fmt.allocPrint(formatter.arena, "tb.{s}.NONE", .{
                        @tagName(flags_type(record.type)),
                    })
                else
                    "0";
                try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
                try writer.print("{s}={s},\n", .{ field_name, value });
            }
        },
        else => {
            for (record.fields) |field| {
                const value = try render_typed_value(formatter, field.field, field.value);
                try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
                try writer.print("{s}={s},\n", .{ field.field.name, value });
            }
        },
    }
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("){s}\n", .{options.suffix});
}

fn emit_assertion(
    formatter: Formatter,
    writer: *std.Io.Writer,
    assertion: ast.Assertion,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert len({s}) == {d}\n", .{ equal.actual, equal.expected.len });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_typed_value(formatter, field.field, field.value);
                    try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                    try writer.print("assert {s}[{d}].{s} == {s}\n", .{
                        equal.actual, index, field.field.name, value,
                    });
                }
            }
        },
        .empty => |actual| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert {s} == []\n", .{actual});
        },
        .unique => |ids| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert len(set({s})) == len({s})\n", .{ ids, ids });
        },
        .ascending => |ids| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print(
                "assert all({s}[i - 1] < {s}[i] for i in range(1, len({s})))\n",
                .{ ids, ids, ids },
            );
        },
        .equal_field => |comparison| {
            const value = switch (comparison.expected) {
                .expression => |expression| try render_typed_value(
                    formatter,
                    comparison.actual.field,
                    expression,
                ),
                .field_reference => |field| try render_field_access(formatter, field),
            };
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert {s}.{s} == {s}\n", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .greater_than => |comparison| {
            const value = try render_typed_value(
                formatter,
                comparison.actual.field,
                comparison.expected.expression,
            );
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert {s}.{s} > {s}\n", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        // The DSL carries no exception type, matching Ruby's `assert_raises(StandardError)`.
        .fail => |call| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("with pytest.raises(Exception):\n");
            try emit_invocation(formatter, writer, call, .{
                .indent_level = formatter.statement_level + 1,
            });
        },
    }
}

fn filter_fields(record_type: ast.Record.Type) []const []const u8 {
    switch (record_type) {
        inline .AccountFilter, .QueryFilter => |comptime_type| {
            return comptime field_names(comptime_type);
        },
        else => unreachable,
    }
}

fn field_names(comptime record_type: ast.Record.Type) []const []const u8 {
    var names: []const []const u8 = &.{};
    for (std.meta.fields(ast.Record.Struct(record_type))) |field| {
        if (std.mem.eql(u8, field.name, "reserved")) continue;
        names = names ++ &[_][]const u8{field.name};
    }
    return names;
}

fn flags_type(record_type: ast.Record.Type) ast.Record.Type {
    return switch (record_type) {
        .AccountFilter => .AccountFilterFlags,
        .QueryFilter => .QueryFilterFlags,
        else => unreachable,
    };
}

fn find_field(record: ast.Record, field_name: []const u8) ?ast.FieldValue {
    for (record.fields) |field| {
        if (std.mem.eql(u8, field.field.name, field_name)) return field;
    }
    return null;
}

fn render_expression(
    formatter: Formatter,
    expression: ast.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "tb.id()",
        .generate_ids => |count| {
            return std.fmt.allocPrint(
                formatter.arena,
                "[tb.id() for _ in range({d})]",
                .{count},
            );
        },
        .call => unreachable,
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                return record.fields[0].value.integer;
            },
            .Account,
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .Transfer,
            .TransferFlags,
            => unreachable,
        },
        .integer => |text| return text,
        .boolean => |value| return if (value) "True" else "False",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return std.fmt.allocPrint(formatter.arena, "{s}[{d}]", .{
                index.reference,
                index.index,
            });
        },
    }
}

fn render_flags(formatter: Formatter, record: ast.Record) ![]const u8 {
    var text = std.Io.Writer.Allocating.init(formatter.arena);
    for (record.fields, 0..) |field, index| {
        assert(field.value == .boolean and field.value.boolean);
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.print("tb.{s}.{s}", .{
            @tagName(record.type),
            try formatter.to_case(.UPPER_CASE, field.field.name),
        });
    }
    return text.written();
}

fn render_field_access(
    formatter: Formatter,
    reference: ast.Assertion.FieldReference,
) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s}.{s}", .{
        reference.reference,
        reference.field.name,
    });
}

fn render_typed_value(
    formatter: Formatter,
    field: ast.Field,
    value: ast.Expression,
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            return std.fmt.allocPrint(formatter.arena, "tb.{s}.{s}", .{
                field.type.enum_name,
                try formatter.to_case(.UPPER_CASE, literal),
            });
        },
        .record => |record| {
            assert(ast.Record.is_flags(record.type));
            return render_flags(formatter, record);
        },
        // Python's int is arbitrary precision, so every integer width renders as decimal text.
        .integer, .generate_id, .boolean, .reference, .index => {
            return render_expression(formatter, value);
        },
        .call, .generate_ids => unreachable,
    }
}
