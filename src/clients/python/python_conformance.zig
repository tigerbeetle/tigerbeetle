const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Arena = conformance.Arena;
const Printer = conformance.Printer;

pub fn main(init: std.process.Init) !void {
    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const stdout_writer = &stdout.interface;
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);
    var printer = Printer.init(&arena, stdout_writer, .{
        .indent_width = 4,
        .comment_marker = "#",
    });

    try emit(&printer);
    try stdout_writer.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => true,
        .requires_fractional_amounts => true,
    };
}

const ClientVariant = enum { synchronous, asynchronous };

fn emit(printer: *Printer) !void {
    try printer.write(
        \\############################################################
        \\## This file was auto-generated by python_conformance.zig ##
        \\##               Do not manually modify.                  ##
        \\############################################################
        \\
        \\import asyncio
        \\import functools
        \\import inspect
        \\import os
        \\import sys
        \\import threading
        \\import time
        \\
        \\import pytest
        \\
        \\import tigerbeetle as tb
        \\
        \\replica_addresses = os.getenv("TB_ADDRESS")
        \\if not replica_addresses:
        \\    print("error: missing TB_ADDRESS environment variable")
        \\    sys.exit(1)
        \\
    );
    for (std.enums.values(ClientVariant)) |variant| {
        try printer.write_empty_line();
        try printer.write(switch (variant) {
            .synchronous =>
            \\#################
            \\## Sync client ##
            \\#################
            \\
            \\@pytest.fixture
            \\def client():
            \\    client = tb.ClientSync(cluster_id=0, replica_addresses=replica_addresses)
            \\    yield client
            \\    client.close()
            \\
            ,
            .asynchronous =>
            \\##################
            \\## Async client ##
            \\##################
            \\
            \\def async_test(case):
            \\    @functools.wraps(case)
            \\    def test():
            \\        async def run():
            \\            client = tb.ClientAsync(cluster_id=0, replica_addresses=replica_addresses)
            \\            try:
            \\                await case(client)
            \\            finally:
            \\                await client.close()
            \\        asyncio.run(run())
            \\    # PEP 362: Stop pytest from treating the test's `client` parameter as a fixture.
            \\    test.__signature__ = inspect.Signature()
            \\    return test
            \\
            ,
        });
        for (conformance.sources) |source| {
            defer printer.arena.reset();

            const suite = try conformance.parse(printer.arena.allocator(), source);
            try printer.write_empty_line();
            try printer.print_indented("# Suite: {s}", .{suite.name});
            for (suite.cases) |case| {
                printer.arena.mark();
                defer printer.arena.restore();

                try printer.write_empty_line();
                if (case.requirement) |requirement| {
                    if (!satisfies(requirement)) {
                        try printer.write_omission(case);
                        continue;
                    }
                }
                const case_name = try printer.to_case_alloc(.snake_case, case.description);
                switch (variant) {
                    .synchronous => try printer.print_indented("def test_{s}_{s}(client):", .{
                        suite.name, case_name,
                    }),
                    .asynchronous => {
                        try printer.write_indented("@async_test");
                        try printer.print_indented("async def test_{s}_{s}_async(client):", .{
                            suite.name, case_name,
                        });
                    },
                }
                printer.indent();
                for (case.steps) |step| try emit_step(printer, step, variant);
                printer.dedent();
            }
        }
    }
}

fn emit_step(printer: *Printer, step: ast.Step, variant: ClientVariant) !void {
    switch (step) {
        .binding => |binding| try emit_binding(printer, binding, variant),
        .call => |call| try emit_call(printer, call, variant, .{}),
        .assertion => |assertion| try emit_assertion(printer, assertion, variant),
        .directive => |directive| try emit_directive(printer, directive, variant),
        .create_client => |arguments| {
            try emit_create_client(printer, arguments, variant, .success);
        },
    }
}

fn emit_create_client(
    printer: *Printer,
    arguments: ast.ClientInitArgs,
    variant: ClientVariant,
    outcome: union(enum) { success, failure: ?ast.ClientError },
) !void {
    const class_name = switch (variant) {
        .synchronous => "ClientSync",
        .asynchronous => "ClientAsync",
    };
    const replica_addresses = switch (arguments.replica_addresses) {
        .server => "replica_addresses",
        .literal => |text| try printer.string_alloc("\"{s}\"", .{text}),
    };
    switch (outcome) {
        .success => try printer.print_indented(
            "{s}tb.{s}(cluster_id={s}, replica_addresses={s}).close()",
            .{
                switch (variant) {
                    .synchronous => "",
                    .asynchronous => "await ",
                },
                class_name,
                arguments.cluster_id,
                replica_addresses,
            },
        ),
        .failure => |client_error| {
            const raises: []const u8, const status: ?[]const u8 =
                if (client_error) |expected| switch (expected) {
                    .address_invalid => .{ "tb.client.InitError", "ADDRESS_INVALID" },
                    .address_limit_exceeded => .{
                        "tb.client.InitError",
                        "ADDRESS_LIMIT_EXCEEDED",
                    },
                    .cluster_id_invalid => .{ "tb.IntegerOverflowError", null },
                    .too_much_data, .client_closed => unreachable,
                } else .{ "Exception", null };
            try printer.print_indented("with pytest.raises({s}){s}:", .{
                raises,
                if (status == null) "" else " as error",
            });
            printer.indent();
            try printer.print_indented("tb.{s}(", .{class_name});
            printer.indent();
            try printer.print_indented("cluster_id={s},", .{arguments.cluster_id});
            try printer.print_indented("replica_addresses={s},", .{replica_addresses});
            printer.dedent();
            try printer.write_indented(")");
            printer.dedent();
            if (status) |name| {
                try printer.print_indented(
                    "assert error.value.args[0] == tb.InitStatus.{s}",
                    .{name},
                );
            }
        },
    }
}

fn emit_directive(
    printer: *Printer,
    directive: ast.HarnessDirective,
    variant: ClientVariant,
) !void {
    switch (directive) {
        .sleep_ms => |ms| switch (variant) {
            .synchronous => try printer.print_indented("time.sleep({d} / 1000)", .{ms}),
            .asynchronous => try printer.print_indented(
                "await asyncio.sleep({d} / 1000)",
                .{ms},
            ),
        },
        .concurrently => |concurrently| {
            try printer.write_indented(switch (variant) {
                .synchronous => "def operation():",
                .asynchronous => "async def operation():",
            });
            printer.indent();
            try emit_call(printer, concurrently.call, variant, .{});
            printer.dedent();
            try printer.write_empty_line();
            switch (variant) {
                .synchronous => {
                    try printer.print_indented(
                        "threads = [threading.Thread(target=operation) for _ in range({d})]",
                        .{concurrently.n},
                    );
                    try printer.write_indented("for thread in threads:");
                    printer.indent();
                    try printer.write_indented("thread.start()");
                    printer.dedent();
                    try printer.write_indented("for thread in threads:");
                    printer.indent();
                    try printer.write_indented("thread.join()");
                    printer.dedent();
                },
                .asynchronous => try printer.print_indented(
                    "await asyncio.gather(*(operation() for _ in range({d})))",
                    .{concurrently.n},
                ),
            }
        },
    }
}

fn emit_binding(printer: *Printer, binding: ast.Binding, variant: ClientVariant) !void {
    switch (binding.value) {
        .generate_id, .index, .field_access => {
            const rendered = try render_expression(printer, binding.value);
            try printer.print_indented("{s} = {s}", .{ binding.name, rendered });
        },
        .generate_ids => |count| {
            try printer.print_indented("{s} = []", .{binding.name});
            try printer.print_indented("for index in range({d}):", .{count});
            printer.indent();
            try printer.print_indented("if index % {d} == 0:", .{ast.ids_between_sleeps});
            printer.indent();
            try printer.write_indented(switch (variant) {
                .synchronous => "time.sleep(0.001)",
                .asynchronous => "await asyncio.sleep(0.001)",
            });
            printer.dedent();
            try printer.print_indented("{s}.append(tb.id())", .{binding.name});
            printer.dedent();
        },
        .call => |call| {
            const prefix = try printer.string_alloc("{s} = ", .{binding.name});
            try emit_call(printer, call, variant, .{ .prefix = prefix });
        },
        .integer,
        .boolean,
        .enum_literal,
        .record,
        .reference,
        .increment,
        .decrement,
        => unreachable,
    }
}

fn emit_call(
    printer: *Printer,
    call: ast.Call,
    variant: ClientVariant,
    options: struct {
        prefix: []const u8 = "",
    },
) !void {
    const await_keyword = switch (variant) {
        .synchronous => "",
        .asynchronous => "await ",
    };
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try printer.print_indented("{s}client.close()", .{await_keyword});
        },
        .create_accounts, .create_transfers => {
            if (call.arguments.len == 0) {
                try printer.print_indented("{s}{s}client.{s}([])", .{
                    options.prefix, await_keyword, @tagName(call.name),
                });
                return;
            }
            try printer.print_indented("{s}{s}client.{s}(", .{
                options.prefix, await_keyword, @tagName(call.name),
            });
            printer.indent();
            try printer.write_indented("[");
            printer.indent();
            for (call.arguments) |argument| {
                try emit_record(printer, argument.record, .{ .suffix = "," });
            }
            printer.dedent();
            try printer.write_indented("]");
            printer.dedent();
            try printer.write_indented(")");
        },
        .lookup_accounts, .lookup_transfers => {
            try printer.write_indent();
            try printer.print("{s}{s}client.{s}([", .{
                options.prefix, await_keyword, @tagName(call.name),
            });
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try printer.write(", ");
                try printer.print("{s}", .{try render_expression(printer, argument)});
            }
            try printer.write("])\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            try printer.print_indented("{s}{s}client.{s}(", .{
                options.prefix, await_keyword, @tagName(call.name),
            });
            printer.indent();
            try emit_record(printer, call.arguments[0].record, .{});
            printer.dedent();
            try printer.write_indented(")");
        },
    }
}

fn emit_record(
    printer: *Printer,
    record: ast.Record,
    options: struct {
        suffix: []const u8 = "",
    },
) !void {
    try printer.print_indented("tb.{s}(", .{@tagName(record.type)});
    printer.indent();
    switch (record.type) {
        .AccountFilter, .QueryFilter => {
            for (filter_fields(record.type)) |field_name| {
                if (find_field(record, field_name)) |field| {
                    try emit_field(printer, field);
                    continue;
                }
                const value = if (std.mem.eql(u8, field_name, "flags"))
                    try printer.string_alloc("tb.{s}.NONE", .{
                        @tagName(flags_type(record.type)),
                    })
                else
                    "0";
                try printer.print_indented("{s}={s},", .{ field_name, value });
            }
        },
        else => {
            for (record.fields) |field| try emit_field(printer, field);
        },
    }
    printer.dedent();
    try printer.print_indented("){s}", .{options.suffix});
}

fn emit_field(printer: *Printer, field: ast.FieldValue) !void {
    if (field.value == .record and
        ast.Record.is_flags(field.value.record.type) and
        field.value.record.fields.len > 1)
    {
        try emit_flags(printer, field.field.name, field.value.record);
    } else {
        const value = try render_typed_value(printer, field.field, field.value);
        try printer.print_indented("{s}={s},", .{ field.field.name, value });
    }
}

fn emit_flags(printer: *Printer, name: []const u8, flags: ast.Record) !void {
    try printer.print_indented("{s}=(", .{name});
    printer.indent();
    try printer.write_indented(try render_flag(printer, flags.type, flags.fields[0]));
    for (flags.fields[1..]) |flag| {
        try printer.print_indented("| {s}", .{try render_flag(printer, flags.type, flag)});
    }
    printer.dedent();
    try printer.write_indented("),");
}

fn emit_assertion(
    printer: *Printer,
    assertion: ast.Assertion,
    variant: ClientVariant,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try printer.print_indented("assert len({s}) == {d}", .{
                equal.actual, equal.expected.len,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_typed_value(printer, field.field, field.value);
                    try printer.print_indented("assert {s}[{d}].{s} == {s}", .{
                        equal.actual, index, field.field.name, value,
                    });
                }
            }
        },
        .empty => |actual| {
            try printer.print_indented("assert {s} == []", .{actual});
        },
        .id_ascending => |ids| {
            try printer.print_indented(
                "assert all({s}[i - 1] < {s}[i] for i in range(1, len({s})))",
                .{ ids, ids, ids },
            );
        },
        .equal_field => |comparison| {
            const value = switch (comparison.expected) {
                .expression => |expression| try render_typed_value(
                    printer,
                    comparison.actual.field,
                    expression,
                ),
                .field_reference => |field| try render_field_access(printer, field),
            };
            try printer.print_indented("assert {s}.{s} == {s}", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .greater_than => |comparison| {
            const value = try render_typed_value(
                printer,
                comparison.actual.field,
                comparison.expected.expression,
            );
            try printer.print_indented("assert {s}.{s} > {s}", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .fail => |failure| switch (failure.action) {
            .call => |call| {
                if (failure.client_error) |client_error| {
                    try printer.print_indented("with pytest.raises(tb.{s}):", .{
                        python_error_name(client_error),
                    });
                } else {
                    try printer.write_indented("with pytest.raises(Exception):");
                }
                printer.indent();
                try emit_call(printer, call, variant, .{});
                printer.dedent();
            },
            .create_client => |arguments| {
                try emit_create_client(printer, arguments, variant, .{
                    .failure = failure.client_error,
                });
            },
        },
    }
}

fn filter_fields(record_type: ast.Record.Type) []const []const u8 {
    switch (record_type) {
        inline .AccountFilter, .QueryFilter => |comptime_type| {
            return comptime field_names(comptime_type);
        },
        else => unreachable,
    }
}

fn field_names(comptime record_type: ast.Record.Type) []const []const u8 {
    var names: []const []const u8 = &.{};
    for (std.meta.fields(ast.Record.Struct(record_type))) |field| {
        if (std.mem.eql(u8, field.name, "reserved")) continue;
        names = names ++ &[_][]const u8{field.name};
    }
    return names;
}

fn flags_type(record_type: ast.Record.Type) ast.Record.Type {
    return switch (record_type) {
        .AccountFilter => .AccountFilterFlags,
        .QueryFilter => .QueryFilterFlags,
        else => unreachable,
    };
}

fn find_field(record: ast.Record, field_name: []const u8) ?ast.FieldValue {
    for (record.fields) |field| {
        if (std.mem.eql(u8, field.field.name, field_name)) return field;
    }
    return null;
}

fn render_expression(
    printer: *Printer,
    expression: ast.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "tb.id()",
        .call, .generate_ids, .record => unreachable,
        .integer => |text| return text,
        .boolean => |value| return if (value) "True" else "False",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return printer.string_alloc("{s}[{d}]", .{
                index.reference,
                index.index,
            });
        },
        .field_access => |access| return render_field_access(printer, access),
        .increment => |arithmetic| return render_arithmetic(printer, arithmetic, "+"),
        .decrement => |arithmetic| return render_arithmetic(printer, arithmetic, "-"),
    }
}

fn python_error_name(client_error: ast.ClientError) []const u8 {
    return switch (client_error) {
        .too_much_data => "TooMuchDataError",
        .client_closed => "ClientClosedError",
        .address_invalid, .address_limit_exceeded, .cluster_id_invalid => unreachable,
    };
}

fn render_flags(printer: *Printer, record: ast.Record) ![]const u8 {
    if (record.fields.len == 0) {
        return printer.string_alloc("tb.{s}.NONE", .{@tagName(record.type)});
    }
    var text = std.Io.Writer.Allocating.init(printer.arena.allocator());
    for (record.fields, 0..) |field, index| {
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.writeAll(try render_flag(printer, record.type, field));
    }
    return text.written();
}

fn render_flag(printer: *Printer, record_type: ast.Record.Type, flag: ast.FieldValue) ![]const u8 {
    assert(flag.value == .boolean and flag.value.boolean);
    return printer.string_alloc("tb.{s}.{s}", .{
        @tagName(record_type),
        try printer.to_case_alloc(.UPPER_CASE, flag.field.name),
    });
}

fn render_field_access(
    printer: *Printer,
    reference: ast.FieldReference,
) ![]const u8 {
    return printer.string_alloc("{s}.{s}", .{
        reference.reference,
        reference.field.name,
    });
}

fn render_arithmetic(
    printer: *Printer,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
) ![]const u8 {
    return printer.string_alloc("{s} {s} {d}", .{
        arithmetic.reference,
        operator,
        arithmetic.by,
    });
}

fn render_typed_value(
    printer: *Printer,
    field: ast.Field,
    value: ast.Expression,
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            return printer.string_alloc("tb.{s}.{s}", .{
                field.type.enum_name,
                try printer.to_case_alloc(.UPPER_CASE, literal),
            });
        },
        .record => |record| {
            assert(ast.Record.is_flags(record.type));
            return render_flags(printer, record);
        },
        .integer,
        .generate_id,
        .boolean,
        .reference,
        .index,
        .field_access,
        .increment,
        .decrement,
        => {
            return render_expression(printer, value);
        },
        .call, .generate_ids => unreachable,
    }
}
