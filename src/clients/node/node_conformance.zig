const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Formatter = conformance.Formatter;

pub fn main(init: std.process.Init) !void {
    const formatter = Formatter.init(conformance.allocator(), .{
        .indent_width = 2,
        .start_level = 0,
    });

    const tests = try conformance.parse(formatter.arena);

    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    try emit(formatter, &stdout.interface, tests);
    try stdout.interface.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        // Amounts are `bigint`s: arbitrary precision, but integral only.
        .requires_unbounded_integers => true,
        .requires_fractional_amounts => false,
    };
}

fn emit(formatter: Formatter, writer: *std.Io.Writer, tests: ast.ConformanceTests) !void {
    try writer.writeAll(
        \\//////////////////////////////////////////////////////////
        \\// This file was auto-generated by node_conformance.zig  //
        \\//               Do not manually modify.                 //
        \\//////////////////////////////////////////////////////////
        \\
        \\import assert, { AssertionError } from 'assert'
        \\import {
        \\  Account,
        \\  AccountFilter,
        \\  AccountFilterFlags,
        \\  AccountFlags,
        \\  Client,
        \\  createClient,
        \\  CreateAccountStatus,
        \\  CreateTransferStatus,
        \\  id,
        \\  QueryFilter,
        \\  QueryFilterFlags,
        \\  Transfer,
        \\  TransferFlags,
        \\} from '.'
        \\
        \\const REPLICA_ADDRESSES = [process.env.TB_ADDRESS || '3000'];
        \\
        \\// Every field is required, so cases spread these and override only what they set.
        \\const account_default: Account = {
        \\  id: 0n,
        \\  debits_pending: 0n,
        \\  debits_posted: 0n,
        \\  credits_pending: 0n,
        \\  credits_posted: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  reserved: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  flags: 0,
        \\  timestamp: 0n,
        \\}
        \\
        \\const transfer_default: Transfer = {
        \\  id: 0n,
        \\  debit_account_id: 0n,
        \\  credit_account_id: 0n,
        \\  amount: 0n,
        \\  pending_id: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  timeout: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  flags: 0,
        \\  timestamp: 0n,
        \\}
        \\
        \\const account_filter_default: AccountFilter = {
        \\  account_id: 0n,
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  code: 0,
        \\  timestamp_min: 0n,
        \\  timestamp_max: 0n,
        \\  limit: 0,
        \\  flags: 0,
        \\}
        \\
        \\const query_filter_default: QueryFilter = {
        \\  user_data_128: 0n,
        \\  user_data_64: 0n,
        \\  user_data_32: 0,
        \\  ledger: 0,
        \\  code: 0,
        \\  timestamp_min: 0n,
        \\  timestamp_max: 0n,
        \\  limit: 0,
        \\  flags: 0,
        \\}
        \\
        \\async function sleep_ms(ms: number): Promise<void> {
        \\  await new Promise(resolve => setTimeout(resolve, ms))
        \\}
        \\
        \\const tests: Array<{ name: string, fn: (client: Client) => Promise<void> }> = []
        \\function test(name: string, fn: (client: Client) => Promise<void>) {
        \\  tests.push({ name, fn })
        \\}
        \\
    );
    for (tests.suites) |suite| {
        try writer.writeAll("\n");
        try writer.print("// Suite: {s}\n", .{suite.name});
        for (suite.cases) |case| {
            try writer.writeAll("\n");
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    const text = try formatter.generate_omission(case);
                    try writer.writeAll(text);
                    continue;
                }
            }
            try writer.print("test('{s}_{s}', async (client) => {{\n", .{
                suite.name,
                try formatter.to_case(.snake_case, case.description),
            });
            try emit_case(formatter, writer, case);
            try writer.writeAll("})\n");
        }
    }
    try writer.writeAll(
        \\
        \\async function main () {
        \\  const start = new Date().getTime()
        \\  for (let i = 0; i < tests.length; i++) {
        \\    const client = createClient({
        \\      cluster_id: 0n,
        \\      replica_addresses: REPLICA_ADDRESSES,
        \\    })
        \\    try {
        \\      await tests[i].fn(client).then(() => {
        \\        console.log(tests[i].name + ": PASSED")
        \\      }).catch(error => {
        \\        console.log(tests[i].name + ": FAILED")
        \\        throw error
        \\      })
        \\    } finally {
        \\      client.destroy()
        \\    }
        \\  }
        \\  const end = new Date().getTime()
        \\  console.log('Time taken (s):', (end - start)/1000)
        \\}
        \\
        \\main().catch((error: AssertionError) => {
        \\  console.log('operator:', error.operator)
        \\  console.log('stack:', error.stack)
        \\  process.exit(-1);
        \\})
        \\
    );
}

fn emit_case(formatter: Formatter, writer: *std.Io.Writer, case: ast.Case) !void {
    for (case.steps) |step| try emit_step(formatter, writer, step);
}

fn emit_step(formatter: Formatter, writer: *std.Io.Writer, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(formatter, writer, binding),
        .call => |call| try emit_call(formatter, writer, call, .{}),
        .assertion => |assertion| try emit_assertion(formatter, writer, assertion),
    }
}

fn emit_binding(formatter: Formatter, writer: *std.Io.Writer, binding: ast.Binding) !void {
    switch (binding.value) {
        .generate_id, .generate_ids, .index, .field_access => {
            try emit_binding_value(formatter, writer, binding.name, binding.value);
        },
        .record => |record| switch (record.type) {
            .U128 => {
                try emit_binding_value(formatter, writer, binding.name, binding.value);
            },
            .Account, .Transfer => {
                const prefix = try std.fmt.allocPrint(formatter.arena, "const {s}: {s} = ", .{
                    binding.name, @tagName(record.type),
                });
                try emit_record(formatter, writer, record, .{
                    .indent_level = formatter.statement_level,
                    .prefix = prefix,
                });
            },
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| {
            const prefix = try std.fmt.allocPrint(formatter.arena, "const {s} = ", .{binding.name});
            try emit_call(formatter, writer, call, .{ .prefix = prefix });
        },
        .integer, .boolean, .enum_literal, .reference, .increment, .decrement => unreachable,
    }
}

fn emit_binding_value(
    formatter: Formatter,
    writer: *std.Io.Writer,
    name: []const u8,
    value: ast.Expression,
) !void {
    const rendered = try render_expression(formatter, value);
    try formatter.write_indent(writer, .{ .level = formatter.statement_level });
    try writer.print("const {s} = {s}\n", .{ name, rendered });
}

fn emit_call(
    formatter: Formatter,
    writer: *std.Io.Writer,
    call: ast.Call,
    options: struct {
        prefix: []const u8 = "",
    },
) !void {
    if (call.concurrency > 1) {
        assert(options.prefix.len == 0);
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("const operations = Array.from({{ length: {d} }}, () =>\n", .{
            call.concurrency,
        });
        try emit_invocation(formatter, writer, call, .{
            .indent_level = formatter.statement_level + 1,
            .awaited = false,
        });
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll(")\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("await Promise.all(operations)\n");
    } else {
        try emit_invocation(formatter, writer, call, .{
            .indent_level = formatter.statement_level,
            .prefix = options.prefix,
        });
    }
}

fn emit_invocation(
    formatter: Formatter,
    writer: *std.Io.Writer,
    call: ast.Call,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        awaited: bool = true,
    },
) !void {
    const awaited = if (options.awaited) "await " else "";
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("client.destroy()\n");
        },
        .sleep_ms => {
            assert(options.prefix.len == 0);
            assert(call.arguments.len == 1);
            const ms = try render_expression(formatter, call.arguments[0]);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("{s}sleep_ms({s})\n", .{ awaited, ms });
        },
        .create_accounts, .create_transfers => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            if (call.arguments.len == 0) {
                try writer.print("{s}{s}client.{s}([])\n", .{
                    options.prefix, awaited, try method_name(formatter, call.name),
                });
                return;
            }
            try writer.print("{s}{s}client.{s}([\n", .{
                options.prefix, awaited, try method_name(formatter, call.name),
            });
            for (call.arguments) |argument| switch (argument) {
                .record => |record| try emit_record(formatter, writer, record, .{
                    .indent_level = options.indent_level + 1,
                    .suffix = ",",
                }),
                .reference => |reference| {
                    try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
                    try writer.print("{s},\n", .{reference});
                },
                else => unreachable,
            };
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("])\n");
        },
        .lookup_accounts, .lookup_transfers => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print("{s}{s}client.{s}([", .{
                options.prefix, awaited, try method_name(formatter, call.name),
            });
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try writer.writeAll(", ");
                try writer.writeAll(try render_id(formatter, argument));
            }
            try writer.writeAll("])\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const prefix = try std.fmt.allocPrint(formatter.arena, "{s}{s}client.{s}(", .{
                options.prefix, awaited, try method_name(formatter, call.name),
            });
            try emit_record(formatter, writer, call.arguments[0].record, .{
                .indent_level = options.indent_level,
                .prefix = prefix,
                .suffix = ")",
            });
        },
    }
}

fn emit_record(
    formatter: Formatter,
    writer: *std.Io.Writer,
    record: ast.Record,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        suffix: []const u8 = "",
    },
) !void {
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("{s}{{\n", .{options.prefix});
    try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
    try writer.print("...{s},\n", .{record_default(record.type)});
    for (record.fields) |field| {
        const value = try render_typed_value(formatter, field.field, field.value);
        try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
        try writer.print("{s}: {s},\n", .{ field.field.name, value });
    }
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("}}{s}\n", .{options.suffix});
}

fn emit_assertion(
    formatter: Formatter,
    writer: *std.Io.Writer,
    assertion: ast.Assertion,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.strictEqual({s}.length, {d})\n", .{
                equal.actual, equal.expected.len,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_typed_value(formatter, field.field, field.value);
                    try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                    try writer.print("assert.strictEqual({s}[{d}].{s}, {s})\n", .{
                        equal.actual, index, field.field.name, value,
                    });
                }
            }
        },
        .empty => |actual| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.strictEqual({s}.length, 0)\n", .{actual});
        },
        .unique => |ids| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.strictEqual(new Set({s}).size, {s}.length)\n", .{ ids, ids });
        },
        .ascending => |ids| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for (let i = 1; i < {s}.length; i++) {{\n", .{ids});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.print("assert.ok({s}[i - 1] < {s}[i])\n", .{ ids, ids });
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .equal_field => |comparison| {
            const value = switch (comparison.expected) {
                .expression => |expression| try render_typed_value(
                    formatter,
                    comparison.actual.field,
                    expression,
                ),
                .field_reference => |field| try render_field_access(formatter, field),
            };
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.strictEqual({s}.{s}, {s})\n", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .greater_than => |comparison| {
            const value = try render_typed_value(
                formatter,
                comparison.actual.field,
                comparison.expected.expression,
            );
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.ok({s}.{s} > {s})\n", .{
                comparison.actual.reference, comparison.actual.field.name, value,
            });
        },
        .fail => |call| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("await assert.rejects(async (): Promise<void> => {\n");
            try emit_invocation(formatter, writer, call, .{
                .indent_level = formatter.statement_level + 1,
            });
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("})\n");
        },
    }
}

fn method_name(formatter: Formatter, name: ast.Call.Name) ![]const u8 {
    return formatter.to_case(.camelCase, @tagName(name));
}

fn record_default(record_type: ast.Record.Type) []const u8 {
    return switch (record_type) {
        .Account => "account_default",
        .Transfer => "transfer_default",
        .AccountFilter => "account_filter_default",
        .QueryFilter => "query_filter_default",
        .AccountBalance,
        .AccountFilterFlags,
        .AccountFlags,
        .CreateAccountResult,
        .CreateTransferResult,
        .QueryFilterFlags,
        .TransferFlags,
        .U128,
        => unreachable,
    };
}

fn render_expression(
    formatter: Formatter,
    expression: ast.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .generate_ids => |count| {
            return std.fmt.allocPrint(
                formatter.arena,
                "Array.from({{ length: {d} }}, () => id())",
                .{count},
            );
        },
        .call => unreachable,
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                return render_bigint(formatter, record.fields[0].value.integer);
            },
            .Account,
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .Transfer,
            .TransferFlags,
            => unreachable,
        },
        .integer => |text| return text,
        .boolean => |value| return if (value) "true" else "false",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return std.fmt.allocPrint(formatter.arena, "{s}[{d}]", .{
                index.reference,
                index.index,
            });
        },
        .field_access => |access| return render_field_access(formatter, access),
        .increment => |arithmetic| return render_arithmetic(formatter, arithmetic, "+"),
        .decrement => |arithmetic| return render_arithmetic(formatter, arithmetic, "-"),
    }
}

// Ids reach the client as `bigint`.
fn render_id(formatter: Formatter, expression: ast.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .reference => |name| return name,
        .integer => |text| return render_bigint(formatter, text),
        else => unreachable,
    }
}

fn render_flags(formatter: Formatter, record: ast.Record) ![]const u8 {
    var text = std.Io.Writer.Allocating.init(formatter.arena);
    for (record.fields, 0..) |field, index| {
        assert(field.value == .boolean and field.value.boolean);
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.print("{s}.{s}", .{ @tagName(record.type), field.field.name });
    }
    return text.written();
}

fn render_field_access(
    formatter: Formatter,
    reference: ast.FieldReference,
) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s}.{s}", .{
        reference.reference,
        reference.field.name,
    });
}

// Only works for 64-bit fields for now because it emits a `bigint`.
fn render_arithmetic(
    formatter: Formatter,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s} {s} {d}n", .{
        arithmetic.reference,
        operator,
        arithmetic.by,
    });
}

fn render_typed_value(
    formatter: Formatter,
    field: ast.Field,
    value: ast.Expression,
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            return std.fmt.allocPrint(formatter.arena, "{s}.{s}", .{
                field.type.enum_name,
                literal,
            });
        },
        .record => |record| {
            assert(ast.Record.is_flags(record.type));
            return render_flags(formatter, record);
        },
        .integer => |text| {
            if (field.type.int >= 64) return render_bigint(formatter, text);
            return text;
        },
        .generate_id,
        .boolean,
        .reference,
        .index,
        .field_access,
        .increment,
        .decrement,
        => {
            return render_expression(formatter, value);
        },
        .call, .generate_ids => unreachable,
    }
}

fn render_bigint(formatter: Formatter, text: []const u8) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s}n", .{text});
}
