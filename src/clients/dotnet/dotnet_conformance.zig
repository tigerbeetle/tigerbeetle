const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Arena = conformance.Arena;
const Printer = conformance.Printer;

pub fn main(init: std.process.Init) !void {
    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const stdout_writer = &stdout.interface;
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);
    var printer = Printer.init(&arena, stdout_writer, .{
        .indent_width = 4,
        .start_level = 1,
    });

    try emit(&printer);
    try stdout_writer.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => false,
        .requires_fractional_amounts => false,
    };
}

const ClientVariant = enum { synchronous, asynchronous };

fn emit(printer: *Printer) !void {
    try printer.write(
        \\////////////////////////////////////////////////////////////
        \\// This file was auto-generated by dotnet_conformance.zig
        \\// Do not manually modify.
        \\////////////////////////////////////////////////////////////
        \\
        \\using Microsoft.VisualStudio.TestTools.UnitTesting;
        \\using System;
        \\using System.Threading;
        \\using System.Threading.Tasks;
        \\
        \\namespace TigerBeetle.Tests;
        \\
        \\[TestClass]
        \\public class ConformanceTests
        \\{
        \\    private static TBServer server = null!;
        \\    private Client client = null!;
        \\
        \\    [ClassInitialize]
        \\    public static void Initialize(TestContext _)
        \\    {
        \\        server = new TBServer();
        \\    }
        \\
        \\    [ClassCleanup]
        \\    public static void Cleanup()
        \\    {
        \\        server.Dispose();
        \\    }
        \\
        \\    [TestInitialize]
        \\    public void CreateClient()
        \\    {
        \\        client = new Client(0, new string[] { server.Address });
        \\    }
        \\
        \\    [TestCleanup]
        \\    public void CloseClient()
        \\    {
        \\        client.Dispose();
        \\    }
        \\
    );
    for (std.enums.values(ClientVariant)) |variant| {
        try printer.write_empty_line();
        try printer.write(switch (variant) {
            .synchronous =>
            \\    /////////////////
            \\    // Sync client
            \\    /////////////////
            \\
            ,
            .asynchronous =>
            \\    //////////////////
            \\    // Async client
            \\    //////////////////
            \\
            \\    // Cases without a request have nothing to await.
            \\#pragma warning disable CS1998
            \\
            ,
        });
        for (conformance.sources) |source| {
            defer printer.arena.reset();

            const suite = try conformance.parse(printer.arena.allocator(), source);
            try printer.write_empty_line();
            try printer.print_indented("// Suite: {s}", .{suite.name});
            for (suite.cases) |case| {
                printer.arena.mark();
                defer printer.arena.restore();

                try printer.write_empty_line();
                if (case.requirement) |requirement| {
                    if (!satisfies(requirement)) {
                        try printer.write_omission(case);
                        continue;
                    }
                }
                try printer.write_indented("[TestMethod]");
                try printer.print_indented("public {s} {s}{s}{s}()", .{
                    switch (variant) {
                        .synchronous => "void",
                        .asynchronous => "async Task",
                    },
                    try printer.to_case_alloc(.PascalCase, suite.name),
                    try printer.to_case_alloc(.PascalCase, case.description),
                    switch (variant) {
                        .synchronous => "",
                        .asynchronous => "Async",
                    },
                });
                try printer.write_indented("{");
                printer.indent();
                for (case.steps) |step| try emit_step(printer, step, variant);
                printer.dedent();
                try printer.write_indented("}");
            }
        }
    }
    try printer.write("#pragma warning restore CS1998\n");
    try printer.write("}\n");
}

fn emit_step(printer: *Printer, step: ast.Step, variant: ClientVariant) !void {
    switch (step) {
        .binding => |binding| try emit_binding(printer, binding, variant),
        .call => |call| try emit_call(printer, call, variant, .{}),
        .assertion => |assertion| try emit_assertion(printer, assertion, variant),
        .directive => |directive| try emit_directive(printer, directive, variant),
        .create_client => |arguments| try emit_create_client(printer, arguments, .success),
    }
}

fn emit_create_client(
    printer: *Printer,
    arguments: ast.ClientInitArgs,
    outcome: union(enum) { success, failure: ?ast.ClientError },
) !void {
    const construction = try printer.string_alloc("new Client({s}, new string[] {{ {s} }})", .{
        try render_uint128(printer, arguments.cluster_id),
        switch (arguments.replica_addresses) {
            .server => "server.Address",
            .literal => |text| try printer.string_alloc("\"{s}\"", .{text}),
        },
    });
    switch (outcome) {
        .success => try printer.print_indented("{s}.Dispose();", .{construction}),
        .failure => |client_error| {
            const status: ?[]const u8 = if (client_error) |expected| switch (expected) {
                .address_invalid => "AddressInvalid",
                .address_limit_exceeded => "AddressLimitExceeded",
                .too_much_data, .client_closed, .cluster_id_invalid => unreachable,
            } else null;
            try printer.print_indented("{s}Assert.ThrowsException<InitializationException>(", .{
                if (status == null) "" else "var exception = ",
            });
            printer.indent();
            try printer.print_indented("() => {s}", .{construction});
            printer.dedent();
            try printer.write_indented(");");
            if (status) |name| {
                try printer.print_indented(
                    "Assert.AreEqual(InitializationStatus.{s}, exception.Status);",
                    .{name},
                );
            }
        },
    }
}

fn emit_directive(
    printer: *Printer,
    directive: ast.HarnessDirective,
    variant: ClientVariant,
) !void {
    switch (directive) {
        .sleep_ms => |ms| try printer.print_indented("Thread.Sleep({d});", .{ms}),
        .concurrently => |concurrently| {
            try printer.print_indented("var tasks = new Task[{d}];", .{concurrently.n});
            try printer.write_indented("for (var index = 0; index < tasks.Length; index++)");
            try printer.write_indented("{");
            printer.indent();
            switch (variant) {
                .synchronous => try emit_call(printer, concurrently.call, variant, .{
                    .prefix = "tasks[index] = Task.Run(() => ",
                    .suffix = ");",
                    .awaited = false,
                }),
                .asynchronous => try emit_call(printer, concurrently.call, variant, .{
                    .prefix = "tasks[index] = ",
                    .suffix = ";",
                    .awaited = false,
                }),
            }
            printer.dedent();
            try printer.write_indented("}");
            try printer.write_indented(switch (variant) {
                .synchronous => "Task.WhenAll(tasks).Wait();",
                .asynchronous => "await Task.WhenAll(tasks);",
            });
        },
    }
}

fn emit_binding(printer: *Printer, binding: ast.Binding, variant: ClientVariant) !void {
    const name = try printer.to_case_alloc(.camelCase, binding.name);
    switch (binding.value) {
        .generate_id => try printer.print_indented("var {s} = ID.Create();", .{name}),
        .generate_ids => |count| {
            try printer.print_indented("var {s} = new UInt128[{d}];", .{ name, count });
            try printer.print_indented(
                "for (var index = 0; index < {s}.Length; index++)",
                .{name},
            );
            try printer.write_indented("{");
            printer.indent();
            try printer.print_indented("if (index % {d} == 0)", .{
                ast.ids_between_sleeps,
            });
            try printer.write_indented("{");
            printer.indent();
            try printer.write_indented("Thread.Sleep(1);");
            printer.dedent();
            try printer.write_indented("}");
            try printer.print_indented("{s}[index] = ID.Create();", .{name});
            printer.dedent();
            try printer.write_indented("}");
        },
        .index => |index| {
            const reference = try printer.to_case_alloc(.camelCase, index.reference);
            try printer.print_indented("var {s} = {s}[{d}];", .{ name, reference, index.index });
        },
        .field_access => |access| {
            try printer.print_indented("var {s} = {s};", .{
                name,
                try render_field_access(printer, access),
            });
        },
        .call => |call| {
            const prefix = try printer.string_alloc("var {s} = ", .{name});
            try emit_call(printer, call, variant, .{ .prefix = prefix });
        },
        .integer,
        .boolean,
        .enum_literal,
        .record,
        .reference,
        .increment,
        .decrement,
        => unreachable,
    }
}

fn emit_call(
    printer: *Printer,
    call: ast.Call,
    variant: ClientVariant,
    options: struct {
        prefix: []const u8 = "",
        suffix: []const u8 = ";",
        awaited: bool = true,
    },
) !void {
    const await_keyword = switch (variant) {
        .synchronous => "",
        .asynchronous => if (options.awaited) "await " else "",
    };
    const method_suffix = switch (variant) {
        .synchronous => "",
        .asynchronous => "Async",
    };
    switch (call.name) {
        .close_client => {
            try printer.print_indented("{s}client.Close(){s}", .{ options.prefix, options.suffix });
        },
        .create_accounts, .create_transfers => {
            const record_type = if (call.name == .create_accounts) "Account" else "Transfer";
            try printer.write_indent();
            try printer.print("{s}{s}client.{s}{s}(", .{
                options.prefix,
                await_keyword,
                dotnet_operation_name(call.name),
                method_suffix,
            });
            if (call.arguments.len == 0) {
                try printer.print("Array.Empty<{s}>()){s}\n", .{ record_type, options.suffix });
                return;
            }
            try printer.print("new {s}[] {{\n", .{record_type});
            printer.indent();
            for (call.arguments) |argument| {
                try printer.write_indented("new()");
                try emit_record_fields(printer, argument.record);
                try printer.write(",\n");
            }
            printer.dedent();
            try printer.print_indented("}}){s}", .{options.suffix});
        },
        .lookup_accounts, .lookup_transfers => {
            try printer.write_indent();
            try printer.print("{s}{s}client.{s}{s}(", .{
                options.prefix,
                await_keyword,
                dotnet_operation_name(call.name),
                method_suffix,
            });
            if (call.arguments.len == 0) {
                try printer.print("Array.Empty<UInt128>()){s}\n", .{options.suffix});
                return;
            }
            try printer.write("new UInt128[] {\n");
            printer.indent();
            for (call.arguments) |argument| {
                try printer.print_indented("{s},", .{try render_id(printer, argument)});
            }
            printer.dedent();
            try printer.print_indented("}}){s}", .{options.suffix});
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const filter = call.arguments[0].record;
            try printer.write_indent();
            try printer.print("{s}{s}client.{s}{s}(new {s}", .{
                options.prefix,
                await_keyword,
                dotnet_operation_name(call.name),
                method_suffix,
                @tagName(filter.type),
            });
            if (filter.fields.len == 0) {
                try printer.print("()){s}\n", .{options.suffix});
                return;
            }
            try printer.write("\n");
            try emit_record_fields(printer, filter);
            try printer.print("){s}\n", .{options.suffix});
        },
    }
}

fn emit_record_fields(printer: *Printer, record: ast.Record) !void {
    try printer.write_indented("{");
    printer.indent();
    for (record.fields) |field| {
        try printer.print_indented("{s} = {s},", .{
            try printer.to_case_alloc(.PascalCase, field.field.name),
            try render_typed_value(printer, field.field, field.value, .{}),
        });
    }
    printer.dedent();
    try printer.write_indent();
    try printer.write("}");
}

fn emit_assertion(printer: *Printer, assertion: ast.Assertion, variant: ClientVariant) !void {
    switch (assertion) {
        .equal => |equal| {
            const actual = try printer.to_case_alloc(.camelCase, equal.actual);
            try printer.print_indented("Assert.AreEqual({d}, {s}.Length);", .{
                equal.expected.len,
                actual,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    try printer.print_indented("Assert.AreEqual({s}, {s}[{d}].{s});", .{
                        try render_typed_value(printer, field.field, field.value, .{
                            .cast = true,
                        }),
                        actual,
                        index,
                        try printer.to_case_alloc(.PascalCase, field.field.name),
                    });
                }
            }
        },
        .equal_field => |comparison| {
            const expected = switch (comparison.expected) {
                .expression => |expression| try render_typed_value(
                    printer,
                    comparison.actual.field,
                    expression,
                    .{ .cast = true },
                ),
                .field_reference => |field| try render_field_access(printer, field),
            };
            try printer.print_indented("Assert.AreEqual({s}, {s});", .{
                expected,
                try render_field_access(printer, comparison.actual),
            });
        },
        .empty => |actual| {
            try printer.print_indented("Assert.AreEqual(0, {s}.Length);", .{
                try printer.to_case_alloc(.camelCase, actual),
            });
        },
        .id_ascending => |ids| {
            const name = try printer.to_case_alloc(.camelCase, ids);
            try printer.print_indented(
                "for (var index = 1; index < {s}.Length; index++)",
                .{name},
            );
            try printer.write_indented("{");
            printer.indent();
            try printer.print_indented("Assert.IsTrue({s}[index - 1] < {s}[index]);", .{
                name,
                name,
            });
            printer.dedent();
            try printer.write_indented("}");
        },
        .greater_than => |comparison| {
            try printer.print_indented("Assert.IsTrue({s} > {s});", .{
                try render_field_access(printer, comparison.actual),
                try render_typed_value(
                    printer,
                    comparison.actual.field,
                    comparison.expected.expression,
                    .{},
                ),
            });
        },
        .fail => |failure| switch (failure.action) {
            .call => |call| {
                const client_error = failure.client_error orelse unreachable;
                try printer.print_indented("{s}<{s}>(", .{
                    switch (variant) {
                        .synchronous => "Assert.ThrowsException",
                        .asynchronous => "await Assert.ThrowsExceptionAsync",
                    },
                    dotnet_exception_name(client_error),
                });
                printer.indent();
                try emit_call(printer, call, variant, .{
                    .prefix = "() => ",
                    .suffix = ");",
                    .awaited = false,
                });
                printer.dedent();
            },
            .create_client => |arguments| {
                try emit_create_client(printer, arguments, .{ .failure = failure.client_error });
            },
        },
    }
}

fn dotnet_exception_name(client_error: ast.ClientError) []const u8 {
    return switch (client_error) {
        .too_much_data => "TooMuchDataException",
        .client_closed => "ClientClosedException",
        .address_invalid, .address_limit_exceeded, .cluster_id_invalid => unreachable,
    };
}

fn render_field_access(printer: *Printer, reference: ast.FieldReference) ![]const u8 {
    return printer.string_alloc("{s}.{s}", .{
        try printer.to_case_alloc(.camelCase, reference.reference),
        try printer.to_case_alloc(.PascalCase, reference.field.name),
    });
}

fn render_typed_value(
    printer: *Printer,
    field: ast.Field,
    value: ast.Expression,
    options: struct { cast: bool = false },
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            return printer.string_alloc("{s}.{s}", .{
                field.type.enum_name,
                try printer.to_case_alloc(.PascalCase, literal),
            });
        },
        .record => |flags| {
            assert(ast.Record.is_flags(flags.type));
            if (flags.fields.len == 0) {
                return printer.string_alloc("{s}.None", .{@tagName(flags.type)});
            }
            var text = std.Io.Writer.Allocating.init(printer.arena.allocator());
            for (flags.fields, 0..) |flag, index| {
                assert(flag.value == .boolean and flag.value.boolean);
                if (index > 0) try text.writer.writeAll(" | ");
                try text.writer.print("{s}.{s}", .{
                    @tagName(flags.type),
                    try printer.to_case_alloc(.PascalCase, flag.field.name),
                });
            }
            return text.written();
        },
        .integer => |text| {
            const bits = field.type.int;
            if (bits == 128 and !fits_ulong(text)) return render_uint128(printer, text);
            if (!options.cast) return text;
            return printer.string_alloc("({s}){s}", .{ integer_type_name(bits), text });
        },
        .generate_id => return "ID.Create()",
        .reference => |name| return printer.to_case_alloc(.camelCase, name),
        .index => |index| {
            return printer.string_alloc("{s}[{d}]", .{
                try printer.to_case_alloc(.camelCase, index.reference),
                index.index,
            });
        },
        .boolean => |boolean| return if (boolean) "true" else "false",
        .field_access => |access| return render_field_access(printer, access),
        .increment => |arithmetic| return render_arithmetic(printer, arithmetic, "+"),
        .decrement => |arithmetic| return render_arithmetic(printer, arithmetic, "-"),
        .call, .generate_ids => unreachable,
    }
}

fn render_arithmetic(
    printer: *Printer,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
) ![]const u8 {
    return printer.string_alloc("{s} {s} {d}", .{
        try printer.to_case_alloc(.camelCase, arithmetic.reference),
        operator,
        arithmetic.by,
    });
}

fn render_id(printer: *Printer, expression: ast.Expression) ![]const u8 {
    return switch (expression) {
        .generate_id => "ID.Create()",
        .reference => |name| printer.to_case_alloc(.camelCase, name),
        .integer => |text| render_uint128(printer, text),
        else => unreachable,
    };
}

fn render_uint128(printer: *Printer, text: []const u8) ![]const u8 {
    if (fits_ulong(text)) return text;
    return printer.string_alloc("UInt128.Parse(\"{s}\")", .{text});
}

fn fits_ulong(text: []const u8) bool {
    const value = std.fmt.parseInt(u128, text, 10) catch unreachable;
    return value <= std.math.maxInt(u64);
}

fn integer_type_name(bits: u16) []const u8 {
    return switch (bits) {
        128 => "UInt128",
        64 => "ulong",
        32 => "uint",
        16 => "ushort",
        8 => "byte",
        else => unreachable,
    };
}

fn dotnet_operation_name(name: ast.Call.Name) []const u8 {
    return switch (name) {
        .create_accounts => "CreateAccounts",
        .create_transfers => "CreateTransfers",
        .lookup_accounts => "LookupAccounts",
        .lookup_transfers => "LookupTransfers",
        .get_account_transfers => "GetAccountTransfers",
        .get_account_balances => "GetAccountBalances",
        .query_accounts => "QueryAccounts",
        .query_transfers => "QueryTransfers",
        .close_client => unreachable,
    };
}
