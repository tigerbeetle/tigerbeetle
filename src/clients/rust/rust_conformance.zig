const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Arena = conformance.Arena;
const Printer = conformance.Printer;

pub fn main(init: std.process.Init) !void {
    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const stdout_writer = &stdout.interface;
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);
    var printer = Printer.init(&arena, stdout_writer, .{
        .indent_width = 4,
        .indent_char = ' ',
        .comment_marker = "//",
    });

    try emit(&printer);
    try stdout_writer.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_fractional_amounts => false,
        .requires_unbounded_integers => false,
        .requires_use_after_close => false,
    };
}

fn emit(printer: *Printer) !void {
    try printer.write(
        \\//////////////////////////////////////////////////////////
        \\// This file was auto-generated by rust_conformance.zig //
        \\//               Do not manually modify.                //
        \\//////////////////////////////////////////////////////////
        \\
        \\#![cfg_attr(rustfmt, rustfmt_skip)]
        \\
        \\use std::cell::UnsafeCell;
        \\use std::sync::{Once, PoisonError};
        \\use std::time::Duration;
        \\
        \\use tigerbeetle as tb;
        \\
        \\mod executor;
        \\use executor::block_on;
        \\
        \\mod test_db;
        \\pub use test_db::*;
        \\
        \\/// The client shared between all cases.
        \\fn client() -> &'static tb::Client {
        \\    struct OnceLock {
        \\        once: Once,
        \\        value: UnsafeCell<Option<tb::Client>>,
        \\    }
        \\
        \\    unsafe impl Sync for OnceLock {}
        \\
        \\    static CLIENT: OnceLock = OnceLock {
        \\        once: Once::new(),
        \\        value: UnsafeCell::new(None),
        \\    };
        \\
        \\    let error_msg = "couldn't create test client";
        \\
        \\    unsafe {
        \\        CLIENT.once.call_once(|| {
        \\            *(&mut *CLIENT.value.get()) =
        \\                Some(tb::Client::new(0, &get_test_db().address()).expect(error_msg));
        \\        });
        \\
        \\        (&*CLIENT.value.get()).as_ref().expect(error_msg)
        \\    }
        \\}
        \\
    );
    for (conformance.sources) |source| {
        defer printer.arena.reset();

        const suite = try conformance.parse(printer.arena.allocator(), source);
        try printer.write_empty_line();
        try printer.print_indented("// Suite: {s}", .{suite.name});
        for (suite.cases) |case| {
            printer.arena.mark();
            defer printer.arena.restore();

            try printer.write_empty_line();
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    try conformance.write_not_applicable(printer, case);
                    continue;
                }
            }
            // Isolated clients are only used for tests that use the client after closing.
            // This is not possible in Rust due to requires_use_after_close == false.
            assert(!case.isolated_client);
            try printer.write_indented("#[test]");
            try printer.print_indented("fn {s}_{s}() -> Result {{", .{
                suite.name,
                try printer.to_case_alloc(.snake_case, case.description),
            });
            printer.indent();
            try printer.print_indented(
                "let _guard = DB_LOCK.{s}().unwrap_or_else(PoisonError::into_inner);",
                .{if (case.exclusive) "write" else "read"},
            );
            try printer.write_indented("block_on(async {");
            printer.indent();
            for (case.steps) |step| try emit_step(printer, step);
            try printer.write_indented("Ok(())");
            printer.dedent();
            try printer.write_indented("})");
            printer.dedent();
            try printer.write_indented("}");
        }
    }
}

fn emit_step(printer: *Printer, step: ast.Step) !void {
    switch (step) {
        .create_client => |arguments| try emit_create_client(printer, arguments, .success),
        .binding => |binding| try emit_binding(printer, binding),
        .call => |call| try emit_call_awaited(printer, call, ""),
        .assertion => |assertion| try emit_assertion(printer, assertion),
        .directive => |directive| try emit_directive(printer, directive),
    }
}

fn emit_create_client(
    printer: *Printer,
    arguments: ast.ClientInitArgs,
    outcome: union(enum) { success, failure: ?ast.ClientError },
) !void {
    const construction = try render_create_client(printer, arguments);
    switch (outcome) {
        .success => try printer.print_indented("{s}?;", .{construction}),
        .failure => |client_error| {
            if (client_error) |expected| {
                try printer.write_indented("assert!(matches!(");
                printer.indent();
                try printer.print_indented("{s},", .{construction});
                try printer.print_indented("Err(tb::InitError::{s})", .{
                    try printer.to_case_alloc(.pascal_case, @tagName(expected)),
                });
                printer.dedent();
                try printer.write_indented("));");
            } else {
                try printer.print_indented("assert!({s}.is_err());", .{construction});
            }
        },
    }
}

fn emit_binding(printer: *Printer, binding: ast.Binding) !void {
    switch (binding.value) {
        .generate_id => try printer.print_indented("let {s} = tb::id();", .{binding.name}),
        .generate_ids => |count| {
            try printer.print_indented("let mut {s} = Vec::new();", .{binding.name});
            try printer.print_indented("for index in 0..{d} {{", .{count});
            printer.indent();
            try printer.print_indented("if index % {d} == 0 {{", .{ast.ids_between_sleeps});
            printer.indent();
            try printer.write_indented("std::thread::sleep(Duration::from_millis(1));");
            printer.dedent();
            try printer.write_indented("}");
            try printer.print_indented("{s}.push(tb::id());", .{binding.name});
            printer.dedent();
            try printer.write_indented("}");
        },
        .index => |index| {
            try printer.print_indented("let {s} = {s}[{d}];", .{
                binding.name,
                index.reference,
                index.index,
            });
        },
        .field_access => |access| {
            try printer.print_indented("let {s} = {s};", .{
                binding.name,
                try render_field_access(printer, access),
            });
        },
        .call => |call| {
            const prefix = try printer.string_alloc("let {s} = ", .{binding.name});
            try emit_call_awaited(printer, call, prefix);
        },
        .integer,
        .boolean,
        .enum_literal,
        .record,
        .reference,
        .increment,
        .decrement,
        => unreachable,
    }
}

fn emit_directive(printer: *Printer, directive: ast.HarnessDirective) !void {
    switch (directive) {
        .sleep_ms => |ms| {
            try printer.print_indented("std::thread::sleep(Duration::from_millis({d}));", .{ms});
        },
        .concurrently => |concurrently| {
            try printer.write_indented("std::thread::scope(|scope| {");
            printer.indent();
            try printer.print_indented("for _ in 0..{d} {{", .{concurrently.n});
            printer.indent();
            try emit_call(printer, concurrently.call, .{
                .prefix = "scope.spawn(|| block_on(",
                .suffix = ").expect(\"concurrent call failed\"));",
            });
            printer.dedent();
            try printer.write_indented("}");
            printer.dedent();
            try printer.write_indented("});");
        },
    }
}

fn emit_call_awaited(printer: *Printer, call: ast.Call, prefix: []const u8) !void {
    if (!arguments_span_lines(call)) {
        return emit_call(printer, call, .{ .prefix = prefix, .suffix = ".await?;" });
    }
    try printer.print_indented("{s}client()", .{prefix});
    printer.indent();
    try printer.write_indent();
    try printer.print(".{s}(", .{@tagName(call.name)});
    try emit_arguments(printer, call);
    try printer.write(")\n");
    try printer.write_indented(".await?;");
    printer.dedent();
}

fn emit_call(
    printer: *Printer,
    call: ast.Call,
    options: struct {
        prefix: []const u8 = "",
        suffix: []const u8,
    },
) !void {
    try printer.write_indent();
    try printer.print("{s}client().{s}(", .{ options.prefix, @tagName(call.name) });
    try emit_arguments(printer, call);
    try printer.print("){s}\n", .{options.suffix});
}

fn arguments_span_lines(call: ast.Call) bool {
    return switch (call.name) {
        .create_accounts, .create_transfers => switch (call.arguments.len) {
            0 => false,
            1 => call.arguments[0].record.fields.len > 0,
            else => true,
        },
        .lookup_accounts, .lookup_transfers => false,
        .get_account_transfers,
        .get_account_balances,
        .query_accounts,
        .query_transfers,
        => call.arguments[0].record.fields.len > 0,
        .close_client => unreachable,
    };
}

fn emit_arguments(printer: *Printer, call: ast.Call) !void {
    switch (call.name) {
        .create_accounts, .create_transfers => switch (call.arguments.len) {
            0 => try printer.write("&[]"),
            1 => {
                try printer.write("&[");
                try emit_record(printer, call.arguments[0].record);
                try printer.write("]");
            },
            else => {
                try printer.write("&[\n");
                printer.indent();
                for (call.arguments) |argument| {
                    try printer.write_indent();
                    try emit_record(printer, argument.record);
                    try printer.write(",\n");
                }
                printer.dedent();
                try printer.write_indent();
                try printer.write("]");
            },
        },
        .lookup_accounts, .lookup_transfers => {
            try printer.write("&[");
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try printer.write(", ");
                try printer.write(render_id(argument));
            }
            try printer.write("]");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            try emit_record(printer, call.arguments[0].record);
        },
        // Closing the shared client requires use after close.
        .close_client => unreachable,
    }
}

fn emit_record(printer: *Printer, record: ast.Record) !void {
    if (record.fields.len == 0) {
        try printer.print("tb::{s}::default()", .{@tagName(record.type)});
        return;
    }
    try printer.print("tb::{s} {{\n", .{@tagName(record.type)});
    printer.indent();
    for (record.fields) |field| {
        if (field.value == .record and field.value.record.fields.len > 1) {
            try emit_flags(printer, field.field.name, field.value.record);
        } else {
            try printer.print_indented("{s}: {s},", .{
                field.field.name,
                try render_value(printer, field.field, field.value),
            });
        }
    }
    try printer.write_indented("..Default::default()");
    printer.dedent();
    try printer.write_indent();
    try printer.write("}");
}

fn emit_assertion(printer: *Printer, assertion: ast.Assertion) !void {
    switch (assertion) {
        .equal => |equal| {
            try printer.print_indented("assert_eq!({s}.len(), {d});", .{
                equal.actual,
                equal.expected.len,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    try printer.print_indented("assert_eq!({s}[{d}].{s}, {s});", .{
                        equal.actual,
                        index,
                        field.field.name,
                        try render_value(printer, field.field, field.value),
                    });
                }
            }
        },
        .equal_field => |comparison| {
            const expected = switch (comparison.expected) {
                .expression => |expression| try render_value(
                    printer,
                    comparison.actual.field,
                    expression,
                ),
                .field_reference => |field| try render_field_access(printer, field),
            };
            try printer.print_indented("assert_eq!({s}, {s});", .{
                try render_field_access(printer, comparison.actual),
                expected,
            });
        },
        .empty => |actual| try printer.print_indented("assert!({s}.is_empty());", .{actual}),
        .id_ascending => |ids| {
            try printer.print_indented(
                "assert!({s}.windows(2).all(|pair| pair[0] < pair[1]));",
                .{ids},
            );
        },
        .greater_than => |comparison| {
            try emit_greater_than(printer, comparison.actual, comparison.expected.expression);
        },
        .all_greater_than => |greater_than| {
            try printer.print_indented("for item in &{s} {{", .{greater_than.actual});
            printer.indent();
            for (greater_than.expected.fields) |field| {
                try emit_greater_than(
                    printer,
                    .{ .reference = "item", .field = field.field },
                    field.value,
                );
            }
            printer.dedent();
            try printer.write_indented("}");
        },
        .fail => |failure| switch (failure.action) {
            .call => |call| {
                // Only cases that Rust omits use `assert_fail` on a call.
                const client_error = failure.client_error orelse unreachable;
                const suffix = try printer.string_alloc(".await, Err(tb::Error::{s})));", .{
                    try printer.to_case_alloc(.pascal_case, @tagName(client_error)),
                });
                try emit_call(printer, call, .{ .prefix = "assert!(matches!(", .suffix = suffix });
            },
            .create_client => |arguments| {
                try emit_create_client(printer, arguments, .{ .failure = failure.client_error });
            },
        },
    }
}

fn emit_greater_than(printer: *Printer, actual: ast.FieldReference, value: ast.Expression) !void {
    try printer.print_indented("assert!({s} > {s});", .{
        try render_field_access(printer, actual),
        try render_value(printer, actual.field, value),
    });
}

fn render_create_client(printer: *Printer, arguments: ast.ClientInitArgs) ![]const u8 {
    return printer.string_alloc("tb::Client::new({s}, {s})", .{
        arguments.cluster_id,
        switch (arguments.replica_addresses) {
            .server => "&get_test_db().address()",
            .literal => |text| try printer.string_alloc("\"{s}\"", .{text}),
        },
    });
}

fn render_field_access(printer: *Printer, reference: ast.FieldReference) ![]const u8 {
    return printer.string_alloc("{s}.{s}", .{ reference.reference, reference.field.name });
}

fn render_value(printer: *Printer, field: ast.Field, value: ast.Expression) ![]const u8 {
    return switch (value) {
        .enum_literal => |literal| printer.string_alloc("tb::{s}::{s}", .{
            field.type.enum_name,
            try printer.to_case_alloc(.pascal_case, literal),
        }),
        .record => |flags| render_flags(printer, flags),
        .integer => |text| text,
        .generate_id => "tb::id()",
        .reference => |name| name,
        .index => |index| printer.string_alloc("{s}[{d}]", .{ index.reference, index.index }),
        .field_access => |access| render_field_access(printer, access),
        .increment => |arithmetic| render_arithmetic(printer, arithmetic, "+"),
        .decrement => |arithmetic| render_arithmetic(printer, arithmetic, "-"),
        .boolean, .call, .generate_ids => unreachable,
    };
}

fn emit_flags(printer: *Printer, name: []const u8, flags: ast.Record) !void {
    assert(ast.Record.is_flags(flags.type));
    assert(flags.fields.len > 1);
    try printer.print_indented("{s}: {s}", .{ name, try render_flag(printer, flags, 0) });
    printer.indent();
    for (1..flags.fields.len) |index| {
        try printer.print_indented("| {s}{s}", .{
            try render_flag(printer, flags, index),
            if (index == flags.fields.len - 1) "," else "",
        });
    }
    printer.dedent();
}

fn render_flags(printer: *Printer, flags: ast.Record) ![]const u8 {
    assert(ast.Record.is_flags(flags.type));
    if (flags.fields.len == 0) {
        return printer.string_alloc("tb::{s}::empty()", .{@tagName(flags.type)});
    }
    var text = std.Io.Writer.Allocating.init(printer.arena.allocator());
    for (0..flags.fields.len) |index| {
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.writeAll(try render_flag(printer, flags, index));
    }
    return text.written();
}

fn render_flag(printer: *Printer, flags: ast.Record, index: usize) ![]const u8 {
    const flag = flags.fields[index];
    assert(flag.value == .boolean and flag.value.boolean);
    return printer.string_alloc("tb::{s}::{s}", .{
        @tagName(flags.type),
        try printer.to_case_alloc(.pascal_case, flag.field.name),
    });
}

fn render_arithmetic(
    printer: *Printer,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
) ![]const u8 {
    return printer.string_alloc("{s} {s} {d}", .{
        arithmetic.reference,
        operator,
        arithmetic.by,
    });
}

fn render_id(expression: ast.Expression) []const u8 {
    return switch (expression) {
        .generate_id => "tb::id()",
        .reference => |name| name,
        .integer => |text| text,
        else => unreachable,
    };
}
