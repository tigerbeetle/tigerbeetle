const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const types = conformance.types;

const indent_width = 2;
const def_indent_level = 1; // class > def
const statement_indent_level = def_indent_level + 1; // class > def > statement

pub fn main(init: std.process.Init) !void {
    var arena_instance = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena_instance.deinit();
    const arena = arena_instance.allocator();

    const tests = try conformance.parse(arena);

    var buffer = std.Io.Writer.Allocating.init(arena);
    try emit(arena, &buffer.writer, tests);
    try std.Io.File.stdout().writeStreamingAll(init.io, buffer.written());
}

fn satisfies(requirement: types.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => true,
    };
}

fn emit(arena: std.mem.Allocator, writer: *std.Io.Writer, tests: types.ConformanceTests) !void {
    try writer.writeAll(
        \\###########################################################
        \\## This file was auto-generated by ruby_conformance.zig ##
        \\##               Do not manually modify.                ##
        \\###########################################################
        \\
        \\require "minitest/autorun"
        \\require "tigerbeetle"
        \\
        \\class TestConformance < Minitest::Test
        \\  def setup
        \\    @tb_address = ENV.fetch("TB_ADDRESS", "3000")
        \\    @client = TigerBeetle::Client.new(cluster_id: 0, replica_addresses: @tb_address)
        \\  end
        \\
        \\  def teardown
        \\    @client&.close
        \\  end
        \\
    );
    for (tests.suites) |suite| {
        try writer.writeAll("\n");
        try write_indent(writer, def_indent_level);
        try writer.print("# Suite: {s}\n", .{suite.name});
        for (suite.cases) |case| {
            try writer.writeAll("\n");
            if (case.requirement) |requirement| assert(satisfies(requirement));
            try write_indent(writer, def_indent_level);
            try writer.print("def test_{s}_", .{suite.name});
            try emit_test_name(writer, case.description);
            try writer.writeAll("\n");
            for (case.steps) |step| try emit_step(arena, writer, step);
            try write_indent(writer, def_indent_level);
            try writer.writeAll("end\n");
        }
    }
    try writer.writeAll("end\n");
}

// Collapses anything that isn't alphanumeric into a single underscore.
fn emit_test_name(writer: *std.Io.Writer, description: []const u8) !void {
    var last_was_underscore = false;
    for (description) |char| {
        if (std.ascii.isAlphanumeric(char)) {
            try writer.writeByte(char);
            last_was_underscore = false;
        } else if (!last_was_underscore) {
            try writer.writeByte('_');
            last_was_underscore = true;
        }
    }
}

fn emit_step(arena: std.mem.Allocator, writer: *std.Io.Writer, step: types.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(arena, writer, binding),
        .call => |call| try emit_call(arena, writer, call, .{}),
        .assertion => |assertion| try emit_assertion(arena, writer, assertion),
    }
}

fn emit_binding(arena: std.mem.Allocator, writer: *std.Io.Writer, binding: types.Binding) !void {
    switch (binding.value) {
        .generate_id, .generate_ids, .index => {
            try emit_binding_value(arena, writer, binding.name, binding.value);
        },
        .record => |record| switch (record.type) {
            .U128, .AccountFlags, .AccountFilterFlags, .QueryFilterFlags, .TransferFlags => {
                try emit_binding_value(arena, writer, binding.name, binding.value);
            },
            .Account,
            .AccountBalance,
            .AccountFilter,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .Transfer,
            => {
                const prefix = try std.fmt.allocPrint(arena, "{s} = ", .{binding.name});
                try emit_record(arena, writer, record, .{
                    .indent_level = statement_indent_level,
                    .prefix = prefix,
                });
            },
        },
        .call => |call| {
            const prefix = try std.fmt.allocPrint(arena, "{s} = ", .{binding.name});
            try emit_call(arena, writer, call, .{ .prefix = prefix });
        },
        .integer, .boolean, .enum_literal, .reference => unreachable,
    }
}

fn emit_binding_value(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    name: []const u8,
    value: types.Expression,
) !void {
    const rendered = try render_expression(arena, value);
    try write_indent(writer, statement_indent_level);
    try writer.print("{s} = {s}\n", .{ name, rendered });
}

fn emit_call(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    call: types.Call,
    options: struct {
        prefix: []const u8 = "",
    },
) !void {
    if (call.concurrency > 1) {
        assert(options.prefix.len == 0);
        try write_indent(writer, statement_indent_level);
        try writer.print("threads = Array.new({d}) do\n", .{call.concurrency});
        try write_indent(writer, 3);
        try writer.writeAll("Thread.new do\n");
        try emit_invocation(arena, writer, call, .{ .indent_level = 4 });
        try write_indent(writer, 3);
        try writer.writeAll("end\n");
        try write_indent(writer, statement_indent_level);
        try writer.writeAll("end\n");
        try write_indent(writer, statement_indent_level);
        try writer.writeAll("threads.each(&:join)\n");
    } else {
        try emit_invocation(arena, writer, call, .{
            .indent_level = statement_indent_level,
            .prefix = options.prefix,
        });
    }
}

fn emit_invocation(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    call: types.Call,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
    },
) !void {
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try write_indent(writer, options.indent_level);
            try writer.print("{s}@client.close\n", .{options.prefix});
        },
        .sleep_ms => {
            assert(options.prefix.len == 0);
            assert(call.arguments.len == 1);
            const ms = try render_expression(arena, call.arguments[0]);
            try write_indent(writer, options.indent_level);
            try writer.print("{s}sleep({s} / 1000.0)\n", .{ options.prefix, ms });
        },
        .create_accounts, .create_transfers, .lookup_accounts, .lookup_transfers => {
            if (!arguments_contain_record(call)) {
                const inline_call = try render_call(arena, call);
                try write_indent(writer, options.indent_level);
                try writer.print("{s}{s}\n", .{ options.prefix, inline_call });
                return;
            }
            try write_indent(writer, options.indent_level);
            try writer.print("{s}@client.{s}(\n", .{ options.prefix, @tagName(call.name) });
            try write_indent(writer, options.indent_level + 1);
            try writer.writeAll("[\n");
            for (call.arguments, 0..) |argument, index| {
                const suffix = if (index < call.arguments.len - 1) "," else "";
                switch (argument) {
                    .record => |record| {
                        try emit_record(arena, writer, record, .{
                            .indent_level = options.indent_level + 2,
                            .suffix = suffix,
                        });
                    },
                    else => {
                        const text = try render_expression(arena, argument);
                        try write_indent(writer, options.indent_level + 2);
                        try writer.print("{s}{s}\n", .{ text, suffix });
                    },
                }
            }
            try write_indent(writer, options.indent_level + 1);
            try writer.writeAll("]\n");
            try write_indent(writer, options.indent_level);
            try writer.writeAll(")\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            try write_indent(writer, options.indent_level);
            try writer.print("{s}@client.{s}(\n", .{ options.prefix, @tagName(call.name) });
            try emit_record(arena, writer, call.arguments[0].record, .{
                .indent_level = options.indent_level + 1,
            });
            try write_indent(writer, options.indent_level);
            try writer.writeAll(")\n");
        },
    }
}

fn emit_record(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    record: types.Record,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        suffix: []const u8 = "",
    },
) !void {
    try write_indent(writer, options.indent_level);
    try writer.print("{s}TigerBeetle::{s}.new(\n", .{ options.prefix, @tagName(record.type) });
    for (record.fields, 0..) |field, index| {
        const value = try render_field_value(arena, field, options.indent_level + 2);
        try write_indent(writer, options.indent_level + 1);
        try writer.print("{s}: {s}", .{ field.name, value });
        if (index < record.fields.len - 1) try writer.writeAll(",");
        try writer.writeAll("\n");
    }
    try write_indent(writer, options.indent_level);
    try writer.print("){s}\n", .{options.suffix});
}

fn emit_assertion(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    assertion: types.Assertion,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert_equal({d}, {s}.length)\n", .{
                equal.expected.len, equal.actual,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_field_value(
                        arena,
                        field,
                        statement_indent_level + 1,
                    );
                    try write_indent(writer, statement_indent_level);
                    try writer.print("assert_equal({s}, {s}[{d}].{s})\n", .{
                        value, equal.actual, index, field.name,
                    });
                }
            }
        },
        .empty => |actual| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert_equal(0, {s}.length)\n", .{actual});
        },
        .unique => |ids| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert_equal({s}.length, {s}.uniq.length)\n", .{ ids, ids });
        },
        .ascending => |ids| {
            try write_indent(writer, statement_indent_level);
            try writer.print("{s}.each_cons(2) {{ |a, b| assert_operator(a, :<, b) }}\n", .{ids});
        },
        .equal_field => |comparison| {
            const actual = try render_field_reference(arena, comparison);
            const value = try render_field_value(
                arena,
                comparison.field,
                statement_indent_level + 1,
            );
            try write_indent(writer, statement_indent_level);
            try writer.print("assert_equal({s}, {s})\n", .{ value, actual });
        },
        .greater_than => |comparison| {
            const actual = try render_field_reference(arena, comparison);
            const value = try render_expression(arena, comparison.field.value);
            try write_indent(writer, statement_indent_level);
            try writer.print("assert_operator({s}, :>, {s})\n", .{ actual, value });
        },
        .fail => |call| {
            try write_indent(writer, statement_indent_level);
            try writer.writeAll("assert_raises(StandardError) do\n");
            try emit_invocation(arena, writer, call, .{
                .indent_level = statement_indent_level + 1,
            });
            try write_indent(writer, statement_indent_level);
            try writer.writeAll("end\n");
        },
    }
}

fn render_field_reference(
    arena: std.mem.Allocator,
    comparison: types.Assertion.FieldComparison,
) ![]const u8 {
    return std.fmt.allocPrint(arena, "{s}.{s}", .{
        comparison.reference, comparison.field.name,
    });
}

fn write_indent(writer: *std.Io.Writer, indent_level: u32) !void {
    try writer.splatByteAll(' ', indent_level * indent_width);
}

fn arguments_contain_record(call: types.Call) bool {
    for (call.arguments) |argument| {
        if (argument == .record) return true;
    }
    return false;
}

fn render_call(arena: std.mem.Allocator, call: types.Call) ![]const u8 {
    assert(!arguments_contain_record(call));
    switch (call.name) {
        .create_accounts, .create_transfers, .lookup_accounts, .lookup_transfers => {
            var text = std.Io.Writer.Allocating.init(arena);
            try text.writer.print("@client.{s}([", .{@tagName(call.name)});
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try text.writer.writeAll(", ");
                try text.writer.writeAll(try render_expression(arena, argument));
            }
            try text.writer.writeAll("])");
            return text.written();
        },
        .close_client,
        .sleep_ms,
        .get_account_transfers,
        .get_account_balances,
        .query_accounts,
        .query_transfers,
        => unreachable,
    }
}

fn render_expression(
    arena: std.mem.Allocator,
    expression: types.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "TigerBeetle.id",
        .generate_ids => |count| {
            return std.fmt.allocPrint(arena, "Array.new({d}) {{ TigerBeetle.id }}", .{count});
        },
        .call => unreachable,
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                return render_expression(arena, record.fields[0].value);
            },
            else => unreachable,
        },
        .integer => |text| return text,
        .boolean => |value| return if (value) "true" else "false",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return std.fmt.allocPrint(arena, "{s}[{d}]", .{ index.reference, index.index });
        },
    }
}

fn render_flags(
    arena: std.mem.Allocator,
    record: types.Record,
    continuation_indent_level: u32,
) ![]const u8 {
    var text = std.Io.Writer.Allocating.init(arena);
    for (record.fields, 0..) |field, index| {
        assert(field.value == .boolean and field.value.boolean);
        if (index > 0) {
            try text.writer.writeAll(" |\n");
            try text.writer.splatByteAll(' ', continuation_indent_level * indent_width);
        }
        try text.writer.print("TigerBeetle::{s}::{s}", .{
            @tagName(record.type), try upper_case(arena, field.name),
        });
    }
    return text.written();
}

fn render_field_value(
    arena: std.mem.Allocator,
    field: types.Field,
    continuation_indent_level: u32,
) ![]const u8 {
    switch (field.value) {
        .enum_literal => |literal| {
            return std.fmt.allocPrint(arena, "TigerBeetle::{s}::{s}", .{
                field.type.enum_name, try upper_case(arena, literal),
            });
        },
        .record => |record| if (types.Record.is_flags(record.type)) {
            return render_flags(arena, record, continuation_indent_level);
        } else {
            return render_expression(arena, field.value);
        },
        else => return render_expression(arena, field.value),
    }
}

fn upper_case(arena: std.mem.Allocator, text: []const u8) ![]const u8 {
    const result = try arena.alloc(u8, text.len);
    return std.ascii.upperString(result, text);
}
