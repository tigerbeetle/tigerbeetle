const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const types = conformance.types;
const Formatter = conformance.Formatter;

pub fn main(init: std.process.Init) !void {
    var arena_instance = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena_instance.deinit();
    const formatter = Formatter.init(arena_instance.allocator(), .{
        .indent_width = 1,
        .indent_char = '\t',
    });

    const tests = try conformance.parse(formatter.arena);

    var buffer = std.Io.Writer.Allocating.init(formatter.arena);
    try emit(formatter, &buffer.writer, tests);
    try std.Io.File.stdout().writeStreamingAll(init.io, buffer.written());
}

fn satisfies(requirement: types.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => false,
    };
}

fn emit(formatter: Formatter, writer: *std.Io.Writer, tests: types.ConformanceTests) !void {
    try writer.writeAll(
        \\///////////////////////////////////////////////////////
        \\// This file was auto-generated by go_conformance.zig //
        \\//              Do not manually modify.               //
        \\///////////////////////////////////////////////////////
        \\
        \\package tigerbeetle_go
        \\
        \\import (
        \\
    );
    try writer.writeAll("\t\"bufio\"\n");
    try writer.writeAll("\t\"bytes\"\n");
    try writer.writeAll("\t\"fmt\"\n");
    try writer.writeAll("\t\"math/rand\"\n");
    try writer.writeAll("\t\"os\"\n");
    try writer.writeAll("\t\"os/exec\"\n");
    try writer.writeAll("\t\"runtime\"\n");
    try writer.writeAll("\t\"strings\"\n");
    try writer.writeAll("\t\"sync\"\n");
    try writer.writeAll("\t\"testing\"\n");
    try writer.writeAll("\t\"time\"\n");
    try writer.writeAll("\n");
    try writer.writeAll("\t\"github.com/tigerbeetle/tigerbeetle-go/assert\"\n");
    try writer.writeAll(")\n");
    try writer.writeAll("\n");
    try writer.writeAll("func TestConformance(t *testing.T) {\n");
    try writer.writeAll("\tport := startConformanceServer(t)\n");
    try writer.writeAll("\n" ++
        "\ttest := func(name string, body func(t *testing.T, client Client)) {\n" ++
        "\t\tt.Run(name, func(t *testing.T) {\n" ++
        "\t\t\tclient := newClient(t, port)\n" ++
        "\t\t\tdefer client.Close()\n" ++
        "\t\t\tbody(t, client)\n" ++
        "\t\t})\n" ++
        "\t}\n");
    for (tests.suites) |suite| {
        try writer.writeAll("\n");
        try formatter.write_indent(writer, .{});
        try writer.print("// Suite: {s}\n", .{suite.name});
        for (suite.cases) |case| {
            try writer.writeAll("\n");
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    const text = try formatter.generate_omission(case);
                    try writer.writeAll(text);
                    continue;
                }
            }
            try formatter.write_indent(writer, .{});
            try writer.print("test(\"{s}_{s}\", func(t *testing.T, client Client) {{\n", .{
                suite.name,
                try formatter.to_case(.snake_case, case.description),
            });
            try emit_case(formatter, writer, case);
            try formatter.write_indent(writer, .{});
            try writer.writeAll("})\n");
        }
    }
    try writer.writeAll("}\n");
    try emit_server(writer);
    try emit_new_client(writer);
}

fn emit_case(formatter: Formatter, writer: *std.Io.Writer, case: types.Case) !void {
    var scope = Scope{ .formatter = formatter };
    for (case.steps) |step| try emit_step(writer, &scope, step);
}

// Tracks what is already declared in the generated `test` body, since Go rejects both a redeclared
// `err` and an unused one.
// TODO: Can we remoe this?
const Scope = struct {
    formatter: Formatter,
    error_declared: bool = false,

    fn error_assign(scope: *Scope, binds_result: bool) []const u8 {
        defer scope.error_declared = true;
        return if (binds_result or !scope.error_declared) ":=" else "=";
    }
};

fn emit_step(writer: *std.Io.Writer, scope: *Scope, step: types.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(writer, scope, binding),
        .call => |call| try emit_call(writer, scope, call, .{}),
        .assertion => |assertion| try emit_assertion(writer, scope, assertion),
    }
}

fn emit_binding(writer: *std.Io.Writer, scope: *Scope, binding: types.Binding) !void {
    const formatter = scope.formatter;
    const name = try formatter.to_case(.GOCamelCase, binding.name);
    switch (binding.value) {
        .generate_id => {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("{s} := ID()\n", .{name});
        },
        .generate_ids => |count| {
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("{s} := make([]Uint128, {d})\n", .{ name, count });
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for i := range {s} {{\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.print("{s}[i] = ID()\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .index => |index| {
            const reference = try formatter.to_case(.GOCamelCase, index.reference);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("{s} := {s}[{d}]\n", .{ name, reference, index.index });
        },
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                const value = try render_uint128(formatter, record.fields[0].value.integer);
                try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                try writer.print("{s} := {s}\n", .{ name, value });
            },
            .Account, .Transfer => {
                const prefix = try std.fmt.allocPrint(formatter.arena, "{s} := ", .{name});
                try emit_record(formatter, writer, record, .{
                    .indent_level = formatter.statement_level,
                    .prefix = prefix,
                    .typed = true,
                });
            },
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| try emit_call(writer, scope, call, .{ .binding = name }),
        .integer, .boolean, .enum_literal, .reference => unreachable,
    }
}

fn emit_call(
    writer: *std.Io.Writer,
    scope: *Scope,
    call: types.Call,
    options: struct {
        binding: ?[]const u8 = null,
        expect_error: bool = false,
    },
) !void {
    const formatter = scope.formatter;
    if (call.concurrency > 1) {
        assert(options.binding == null);
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("var wg sync.WaitGroup\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.print("for i := 0; i < {d}; i++ {{\n", .{call.concurrency});
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("wg.Add(1)\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("go func() {\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
        try writer.writeAll("defer wg.Done()\n");

        var goroutine_scope = Scope{ .formatter = formatter };
        try emit_invocation(writer, &goroutine_scope, call, .{
            .indent_level = formatter.statement_level + 2,
            .error_action = .goroutine,
        });

        try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
        try writer.writeAll("}()\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("}\n");
        try formatter.write_indent(writer, .{ .level = formatter.statement_level });
        try writer.writeAll("wg.Wait()\n");
        return;
    }

    try emit_invocation(writer, scope, call, .{
        .indent_level = formatter.statement_level,
        .binding = options.binding,
        .error_action = if (options.expect_error) .expected else .fatal,
    });
}

const ErrorAction = enum { fatal, goroutine, expected };

fn emit_invocation(
    writer: *std.Io.Writer,
    scope: *Scope,
    call: types.Call,
    options: struct {
        indent_level: u32,
        binding: ?[]const u8 = null,
        error_action: ErrorAction,
    },
) !void {
    const formatter = scope.formatter;
    switch (call.name) {
        .close_client => {
            assert(options.binding == null);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("client.Close()\n");
            return;
        },
        .sleep_ms => {
            assert(options.binding == null);
            assert(call.arguments.len == 1);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.print(
                "time.Sleep({s} * time.Millisecond)\n",
                .{call.arguments[0].integer},
            );
            return;
        },
        else => {},
    }

    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("{s}, err {s} client.{s}(", .{
        options.binding orelse "_",
        scope.error_assign(options.binding != null),
        go_operation_name(call.name),
    });

    switch (call.name) {
        .create_accounts, .create_transfers => {
            const record_type: types.Record.Type =
                if (call.name == .create_accounts) .Account else .Transfer;
            try writer.print("[]{s}{{\n", .{@tagName(record_type)});
            for (call.arguments) |argument| switch (argument) {
                .record => |record| try emit_record(formatter, writer, record, .{
                    .indent_level = options.indent_level + 1,
                    .suffix = ",",
                }),
                .reference => |reference| {
                    try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
                    try writer.print("{s},\n", .{
                        try formatter.to_case(.GOCamelCase, reference),
                    });
                },
                else => unreachable,
            };
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("})\n");
        },
        .lookup_accounts, .lookup_transfers => {
            try writer.writeAll("[]Uint128{");
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try writer.writeAll(", ");
                try writer.writeAll(try render_id(formatter, argument));
            }
            try writer.writeAll("})\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const filter = call.arguments[0].record;
            try writer.print("{s}{{\n", .{@tagName(filter.type)});
            try emit_record_fields(formatter, writer, filter, options.indent_level + 1);
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("})\n");
        },
        .close_client, .sleep_ms => unreachable,
    }

    switch (options.error_action) {
        .fatal => try emit_error_check(formatter, writer, options.indent_level),
        .goroutine => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("if err != nil {\n");
            try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
            try writer.writeAll("t.Error(err)\n");
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("}\n");
        },
        .expected => {
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("if err == nil {\n");
            try formatter.write_indent(writer, .{ .level = options.indent_level + 1 });
            try writer.writeAll("t.Fatal(\"expected an error\")\n");
            try formatter.write_indent(writer, .{ .level = options.indent_level });
            try writer.writeAll("}\n");
        },
    }
}

fn emit_error_check(formatter: Formatter, writer: *std.Io.Writer, indent_level: u32) !void {
    try formatter.write_indent(writer, .{ .level = indent_level });
    try writer.writeAll("if err != nil {\n");
    try formatter.write_indent(writer, .{ .level = indent_level + 1 });
    try writer.writeAll("t.Fatal(err)\n");
    try formatter.write_indent(writer, .{ .level = indent_level });
    try writer.writeAll("}\n");
}

fn emit_record(
    formatter: Formatter,
    writer: *std.Io.Writer,
    record: types.Record,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        suffix: []const u8 = "",
        typed: bool = false,
    },
) !void {
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    if (options.typed) {
        try writer.print("{s}{s}{{\n", .{ options.prefix, @tagName(record.type) });
    } else {
        try writer.print("{s}{{\n", .{options.prefix});
    }
    try emit_record_fields(formatter, writer, record, options.indent_level + 1);
    try formatter.write_indent(writer, .{ .level = options.indent_level });
    try writer.print("}}{s}\n", .{options.suffix});
}

// Pads field names so values line up, which is what gofmt does to a multi-line composite literal.
fn emit_record_fields(
    formatter: Formatter,
    writer: *std.Io.Writer,
    record: types.Record,
    indent_level: u32,
) !void {
    var name_width: usize = 0;
    for (record.fields) |field| {
        const name = try formatter.to_case(.GOPascalCase, field.name);
        name_width = @max(name_width, name.len);
    }
    for (record.fields) |field| {
        const name = try formatter.to_case(.GOPascalCase, field.name);
        const value = try render_field_value(formatter, field);
        try formatter.write_indent(writer, .{ .level = indent_level });
        try writer.print("{s}:", .{name});
        try writer.splatByteAll(' ', name_width - name.len + 1);
        try writer.print("{s},\n", .{value});
    }
}

fn emit_assertion(writer: *std.Io.Writer, scope: *Scope, assertion: types.Assertion) !void {
    const formatter = scope.formatter;
    switch (assertion) {
        .equal => |equal| {
            const actual = try formatter.to_case(.GOCamelCase, equal.actual);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.Len(t, {s}, {d})\n", .{ actual, equal.expected.len });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_field_value(formatter, field);
                    try formatter.write_indent(writer, .{ .level = formatter.statement_level });
                    try writer.print("assert.Equal(t, {s}, {s}[{d}].{s})\n", .{
                        value,
                        actual,
                        index,
                        try formatter.to_case(.GOPascalCase, field.name),
                    });
                }
            }
        },
        .empty => |actual| {
            const name = try formatter.to_case(.GOCamelCase, actual);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.Len(t, {s}, 0)\n", .{name});
        },
        .unique => |ids| {
            const name = try formatter.to_case(.GOCamelCase, ids);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("seen := make(map[string]struct{{}}, len({s}))\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for _, id := range {s} {{\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.writeAll("if _, ok := seen[id.String()]; ok {\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
            try writer.writeAll("t.Fatal(\"duplicate id\")\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.writeAll("}\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.writeAll("seen[id.String()] = struct{}{}\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .ascending => |ids| {
            const name = try formatter.to_case(.GOCamelCase, ids);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("for i := 1; i < len({s}); i++ {{\n", .{name});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.print(
                "if {s}[i-1].BigInt().Cmp({s}[i].BigInt()) >= 0 {{\n",
                .{ name, name },
            );
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 2 });
            try writer.writeAll("t.Fatal(\"ids are not ascending\")\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level + 1 });
            try writer.writeAll("}\n");
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.writeAll("}\n");
        },
        .equal_field => |comparison| {
            const actual = try render_field_reference(formatter, comparison);
            const value = try render_field_value(formatter, comparison.field);
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.Equal(t, {s}, {s})\n", .{ value, actual });
        },
        .greater_than => |comparison| {
            // `assert.Greater` type-asserts both sides to `uint64` rather than converting.
            const bits = comparison.field.type.int;
            if (bits > 64) @panic("assert_greater_than has no Go form for a u128 field");
            const reference = try render_field_reference(formatter, comparison);
            const actual = if (bits == 64)
                reference
            else
                try std.fmt.allocPrint(formatter.arena, "uint64({s})", .{reference});
            try formatter.write_indent(writer, .{ .level = formatter.statement_level });
            try writer.print("assert.Greater(t, {s}, uint64({s}))\n", .{
                actual,
                comparison.field.value.integer,
            });
        },
        .fail => |call| try emit_call(writer, scope, call, .{ .expect_error = true }),
    }
}

fn render_field_reference(
    formatter: Formatter,
    comparison: types.Assertion.FieldComparison,
) ![]const u8 {
    return std.fmt.allocPrint(formatter.arena, "{s}.{s}", .{
        try formatter.to_case(.GOCamelCase, comparison.reference),
        try formatter.to_case(.GOPascalCase, comparison.field.name),
    });
}

fn render_field_value(formatter: Formatter, field: types.Field) ![]const u8 {
    switch (field.value) {
        .enum_literal => |literal| {
            const enum_name = field.type.enum_name;
            return std.fmt.allocPrint(formatter.arena, "{s}{s}", .{
                go_enum_prefix(enum_name),
                try formatter.to_case(.GOPascalCase, literal),
            });
        },
        .record => |flags| {
            assert(types.Record.is_flags(flags.type));
            var text = std.Io.Writer.Allocating.init(formatter.arena);
            try text.writer.print("{s}{{", .{@tagName(flags.type)});
            for (flags.fields, 0..) |flag, index| {
                assert(flag.value == .boolean and flag.value.boolean);
                if (index > 0) try text.writer.writeAll(", ");
                const name = try formatter.to_case(.GOPascalCase, flag.name);
                try text.writer.print("{s}: true", .{name});
            }
            try text.writer.print("}}.ToUint{d}()", .{flags_bits(flags.type)});
            return text.written();
        },
        .integer => |text| {
            const bits = field.type.int;
            if (bits == 128) return render_uint128(formatter, text);
            return text;
        },
        .generate_id => return "ID()",
        .reference => |name| return formatter.to_case(.GOCamelCase, name),
        .index => |index| {
            return std.fmt.allocPrint(formatter.arena, "{s}[{d}]", .{
                try formatter.to_case(.GOCamelCase, index.reference),
                index.index,
            });
        },
        .boolean => |value| return if (value) "true" else "false",
        .call, .generate_ids => unreachable,
    }
}

// Ids reach the client as `Uint128`.
fn render_id(formatter: Formatter, expression: types.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "ID()",
        .reference => |name| return formatter.to_case(.GOCamelCase, name),
        .integer => |text| return render_uint128(formatter, text),
        else => unreachable,
    }
}

fn render_uint128(formatter: Formatter, text: []const u8) ![]const u8 {
    const value = std.fmt.parseInt(u128, text, 10) catch unreachable;
    if (value <= std.math.maxInt(u64)) {
        return std.fmt.allocPrint(formatter.arena, "ToUint128({s})", .{text});
    }

    var bytes: [16]u8 = undefined;
    std.mem.writeInt(u128, &bytes, value, .little);
    var literal = std.Io.Writer.Allocating.init(formatter.arena);
    try literal.writer.writeAll("BytesToUint128([16]byte{");
    for (bytes, 0..) |byte, index| {
        if (index > 0) try literal.writer.writeAll(", ");
        try literal.writer.print("0x{x:0>2}", .{byte});
    }
    try literal.writer.writeAll("})");
    return literal.written();
}

fn go_operation_name(name: types.Call.Name) []const u8 {
    return switch (name) {
        .create_accounts => "CreateAccounts",
        .create_transfers => "CreateTransfers",
        .lookup_accounts => "LookupAccounts",
        .lookup_transfers => "LookupTransfers",
        .get_account_transfers => "GetAccountTransfers",
        .get_account_balances => "GetAccountBalances",
        .query_accounts => "QueryAccounts",
        .query_transfers => "QueryTransfers",
        .close_client, .sleep_ms => unreachable,
    };
}

// Go prefixes status names with the event: `CreateAccountStatus.created` is `AccountCreated`.
fn go_enum_prefix(enum_name: []const u8) []const u8 {
    if (std.mem.eql(u8, enum_name, "CreateAccountStatus")) return "Account";
    if (std.mem.eql(u8, enum_name, "CreateTransferStatus")) return "Transfer";
    @panic("unmapped enum type");
}

fn flags_bits(flags_type: types.Record.Type) u16 {
    return switch (flags_type) {
        .AccountFlags, .TransferFlags => 16,
        .AccountFilterFlags, .QueryFilterFlags => 32,
        else => unreachable,
    };
}

fn emit_server(writer: *std.Io.Writer) !void {
    try writer.writeAll("\n" ++
        "func startConformanceServer(t *testing.T) string {\n" ++
        "\tvar tigerbeetlePath string\n" ++
        "\tif runtime.GOOS == \"windows\" {\n" ++
        "\t\ttigerbeetlePath = \"../../../tigerbeetle.exe\"\n" ++
        "\t} else {\n" ++
        "\t\ttigerbeetlePath = \"../../../tigerbeetle\"\n" ++
        "\t}\n" ++
        "\n" ++
        "\treplicaArg := fmt.Sprintf(\"--replica=%d\", TIGERBEETLE_REPLICA_ID)\n" ++
        "\treplicaCountArg := fmt.Sprintf(\"--replica-count=%d\", TIGERBEETLE_REPLICA_COUNT)\n" ++
        "\tclusterArg := fmt.Sprintf(\"--cluster=%d\", TIGERBEETLE_CLUSTER_ID)\n" ++
        "\n" ++
        "\tfileName := fmt.Sprintf(\"./%d_%d_%d.tigerbeetle\", TIGERBEETLE_CLUSTER_ID, " ++
        "TIGERBEETLE_REPLICA_ID, rand.Int())\n" ++
        "\tt.Cleanup(func() {\n" ++
        "\t\t_ = os.Remove(fileName)\n" ++
        "\t})\n" ++
        "\n" ++
        "\ttbInit := exec.Command(tigerbeetlePath, \"format\", clusterArg, replicaArg, " ++
        "replicaCountArg, fileName)\n" ++
        "\tvar tbErr bytes.Buffer\n" ++
        "\ttbInit.Stdout = &tbErr\n" ++
        "\ttbInit.Stderr = &tbErr\n" ++
        "\tif err := tbInit.Run(); err != nil {\n" ++
        "\t\tfmt.Println(fmt.Sprint(err) + \": \" + tbErr.String())\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\n" ++
        "\ttbStart := exec.Command(tigerbeetlePath,\n" ++
        "\t\t\"start\",\n" ++
        "\t\t\"--development\",\n" ++
        "\t\t\"--addresses=0\",\n" ++
        "\t\tfileName)\n" ++
        "\n" ++
        "\tif testing.Verbose() {\n" ++
        "\t\ttbStart.Stderr = os.Stderr\n" ++
        "\t}\n" ++
        "\n" ++
        "\t// Stdin is not used,\n" ++
        "\t// but when running with `--addresses=0`, the replica exits if stdin is closed.\n" ++
        "\tstdin, err := tbStart.StdinPipe()\n" ++
        "\tif err != nil {\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\t_ = stdin\n" ++
        "\n" ++
        "\t// Stdout is used to read the assigned TCP port.\n" ++
        "\tstdout, err := tbStart.StdoutPipe()\n" ++
        "\tif err != nil {\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\n" ++
        "\tif err := tbStart.Start(); err != nil {\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\tt.Cleanup(func() {\n" ++
        "\t\tif err := tbStart.Process.Kill(); err != nil {\n" ++
        "\t\t\tt.Fatal(err)\n" ++
        "\t\t}\n" ++
        "\t})\n" ++
        "\n" ++
        "\treader := bufio.NewReader(stdout)\n" ++
        "\tport, err := reader.ReadString('\\n')\n" ++
        "\tif err != nil {\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\n" ++
        "\treturn strings.TrimSpace(port)\n" ++
        "}\n");
}

fn emit_new_client(writer: *std.Io.Writer) !void {
    try writer.writeAll("\n" ++
        "func newClient(t *testing.T, port string) Client {\n" ++
        "\tclient, err := NewClient(ToUint128(TIGERBEETLE_CLUSTER_ID), []string{port})\n" ++
        "\tif err != nil {\n" ++
        "\t\tt.Fatal(err)\n" ++
        "\t}\n" ++
        "\n" ++
        "\treturn client\n" ++
        "}\n");
}
