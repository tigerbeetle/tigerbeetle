fn emit_case(arena: std.mem.Allocator, writer: *std.Io.Writer, case: types.Case) !void {
    for (case.steps) |step| try emit_step(arena, writer, step);
}

// Collapses anything that isn't alphanumeric into a single underscore.
fn emit_test_name(writer: *std.Io.Writer, description: []const u8) !void {
    var last_was_underscore = false;
    for (description) |char| {
        if (std.ascii.isAlphanumeric(char)) {
            try writer.writeByte(char);
            last_was_underscore = false;
        } else if (!last_was_underscore) {
            try writer.writeByte('_');
            last_was_underscore = true;
        }
    }
}

fn emit_step(arena: std.mem.Allocator, writer: *std.Io.Writer, step: types.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(arena, writer, binding),
        .call => |call| try emit_call(arena, writer, call, .{}),
        .assertion => |assertion| try emit_assertion(arena, writer, assertion),
    }
}

fn emit_binding(arena: std.mem.Allocator, writer: *std.Io.Writer, binding: types.Binding) !void {
    switch (binding.value) {
        .generate_id, .generate_ids, .index => {
            try emit_binding_value(arena, writer, binding.name, binding.value);
        },
        .record => |record| switch (record.type) {
            .U128 => {
                try emit_binding_value(arena, writer, binding.name, binding.value);
            },
            .Account, .Transfer => {
                const prefix = try std.fmt.allocPrint(arena, "const {s}: {s} = ", .{
                    binding.name, @tagName(record.type),
                });
                try emit_record(arena, writer, record, .{
                    .indent_level = statement_indent_level,
                    .prefix = prefix,
                });
            },
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| {
            const prefix = try std.fmt.allocPrint(arena, "const {s} = ", .{binding.name});
            try emit_call(arena, writer, call, .{ .prefix = prefix });
        },
        .integer, .boolean, .enum_literal, .reference => unreachable,
    }
}

fn emit_binding_value(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    name: []const u8,
    value: types.Expression,
) !void {
    const rendered = try render_expression(arena, value);
    try write_indent(writer, statement_indent_level);
    try writer.print("const {s} = {s}\n", .{ name, rendered });
}

fn emit_call(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    call: types.Call,
    options: struct {
        prefix: []const u8 = "",
    },
) !void {
    if (call.concurrency > 1) {
        assert(options.prefix.len == 0);
        try write_indent(writer, statement_indent_level);
        try writer.print("const operations = Array.from({{ length: {d} }}, () =>\n", .{
            call.concurrency,
        });
        try emit_invocation(arena, writer, call, .{
            .indent_level = statement_indent_level + 1,
            .awaited = false,
        });
        try write_indent(writer, statement_indent_level);
        try writer.writeAll(")\n");
        try write_indent(writer, statement_indent_level);
        try writer.writeAll("await Promise.all(operations)\n");
    } else {
        try emit_invocation(arena, writer, call, .{
            .indent_level = statement_indent_level,
            .prefix = options.prefix,
        });
    }
}

fn emit_invocation(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    call: types.Call,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        awaited: bool = true,
    },
) !void {
    const awaited = if (options.awaited) "await " else "";
    switch (call.name) {
        .close_client => {
            assert(options.prefix.len == 0);
            try write_indent(writer, options.indent_level);
            try writer.writeAll("client.destroy()\n");
        },
        .sleep_ms => {
            assert(options.prefix.len == 0);
            assert(call.arguments.len == 1);
            const ms = try render_expression(arena, call.arguments[0]);
            try write_indent(writer, options.indent_level);
            try writer.print("{s}sleep_ms({s})\n", .{ awaited, ms });
        },
        .create_accounts, .create_transfers => {
            try write_indent(writer, options.indent_level);
            try writer.print("{s}{s}client.{s}([\n", .{
                options.prefix, awaited, try method_name(arena, call.name),
            });
            for (call.arguments) |argument| switch (argument) {
                .record => |record| try emit_record(arena, writer, record, .{
                    .indent_level = options.indent_level + 1,
                    .suffix = ",",
                }),
                .reference => |reference| {
                    try write_indent(writer, options.indent_level + 1);
                    try writer.print("{s},\n", .{reference});
                },
                else => unreachable,
            };
            try write_indent(writer, options.indent_level);
            try writer.writeAll("])\n");
        },
        .lookup_accounts, .lookup_transfers => {
            try write_indent(writer, options.indent_level);
            try writer.print("{s}{s}client.{s}([", .{
                options.prefix, awaited, try method_name(arena, call.name),
            });
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try writer.writeAll(", ");
                try writer.writeAll(try render_id(arena, argument));
            }
            try writer.writeAll("])\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const prefix = try std.fmt.allocPrint(arena, "{s}{s}client.{s}(", .{
                options.prefix, awaited, try method_name(arena, call.name),
            });
            try emit_record(arena, writer, call.arguments[0].record, .{
                .indent_level = options.indent_level,
                .prefix = prefix,
                .suffix = ")",
            });
        },
    }
}

fn emit_record(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    record: types.Record,
    options: struct {
        indent_level: u32,
        prefix: []const u8 = "",
        suffix: []const u8 = "",
    },
) !void {
    try write_indent(writer, options.indent_level);
    try writer.print("{s}{{\n", .{options.prefix});
    try write_indent(writer, options.indent_level + 1);
    try writer.print("...{s},\n", .{record_default(record.type)});
    for (record.fields) |field| {
        const value = try render_field_value(arena, field);
        try write_indent(writer, options.indent_level + 1);
        try writer.print("{s}: {s},\n", .{ field.name, value });
    }
    try write_indent(writer, options.indent_level);
    try writer.print("}}{s}\n", .{options.suffix});
}

fn emit_assertion(
    arena: std.mem.Allocator,
    writer: *std.Io.Writer,
    assertion: types.Assertion,
) !void {
    switch (assertion) {
        .equal => |equal| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert.strictEqual({s}.length, {d})\n", .{
                equal.actual, equal.expected.len,
            });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_field_value(arena, field);
                    try write_indent(writer, statement_indent_level);
                    try writer.print("assert.strictEqual({s}[{d}].{s}, {s})\n", .{
                        equal.actual, index, field.name, value,
                    });
                }
            }
        },
        .empty => |actual| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert.strictEqual({s}.length, 0)\n", .{actual});
        },
        .unique => |ids| {
            try write_indent(writer, statement_indent_level);
            try writer.print("assert.strictEqual(new Set({s}).size, {s}.length)\n", .{ ids, ids });
        },
        .ascending => |ids| {
            try write_indent(writer, statement_indent_level);
            try writer.print("for (let i = 1; i < {s}.length; i++) {{\n", .{ids});
            try write_indent(writer, statement_indent_level + 1);
            try writer.print("assert.ok({s}[i - 1] < {s}[i])\n", .{ ids, ids });
            try write_indent(writer, statement_indent_level);
            try writer.writeAll("}\n");
        },
        .equal_field => |comparison| {
            const value = try render_field_value(arena, comparison.field);
            try write_indent(writer, statement_indent_level);
            try writer.print("assert.strictEqual({s}.{s}, {s})\n", .{
                comparison.reference, comparison.field.name, value,
            });
        },
        .greater_than => |comparison| {
            const value = try render_field_value(arena, comparison.field);
            try write_indent(writer, statement_indent_level);
            try writer.print("assert.ok({s}.{s} > {s})\n", .{
                comparison.reference, comparison.field.name, value,
            });
        },
        .fail => |call| {
            try write_indent(writer, statement_indent_level);
            try writer.writeAll("await assert.rejects(async (): Promise<void> => {\n");
            try emit_invocation(arena, writer, call, .{
                .indent_level = statement_indent_level + 1,
            });
            try write_indent(writer, statement_indent_level);
            try writer.writeAll("})\n");
        },
    }
}

fn write_indent(writer: *std.Io.Writer, indent_level: u32) !void {
    try writer.splatByteAll(' ', indent_level * indent_width);
}

fn method_name(arena: std.mem.Allocator, name: types.Call.Name) ![]const u8 {
    return utils.to_case(arena, .camelCase, @tagName(name));
}

fn record_default(record_type: types.Record.Type) []const u8 {
    return switch (record_type) {
        .Account => "account_default",
        .Transfer => "transfer_default",
        .AccountFilter => "account_filter_default",
        .QueryFilter => "query_filter_default",
        .AccountBalance,
        .AccountFilterFlags,
        .AccountFlags,
        .CreateAccountResult,
        .CreateTransferResult,
        .QueryFilterFlags,
        .TransferFlags,
        .U128,
        => unreachable,
    };
}

fn render_expression(
    arena: std.mem.Allocator,
    expression: types.Expression,
) std.mem.Allocator.Error![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .generate_ids => |count| {
            return std.fmt.allocPrint(
                arena,
                "Array.from({{ length: {d} }}, () => id())",
                .{count},
            );
        },
        .call => unreachable,
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                return render_bigint(arena, record.fields[0].value.integer);
            },
            .Account,
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .Transfer,
            .TransferFlags,
            => unreachable,
        },
        .integer => |text| return text,
        .boolean => |value| return if (value) "true" else "false",
        .enum_literal => unreachable,
        .reference => |name| return name,
        .index => |index| {
            return std.fmt.allocPrint(arena, "{s}[{d}]", .{ index.reference, index.index });
        },
    }
}

// Ids reach the client as `bigint`.
fn render_id(arena: std.mem.Allocator, expression: types.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "id()",
        .reference => |name| return name,
        .integer => |text| return render_bigint(arena, text),
        else => unreachable,
    }
}

fn render_flags(arena: std.mem.Allocator, record: types.Record) ![]const u8 {
    var text = std.Io.Writer.Allocating.init(arena);
    for (record.fields, 0..) |field, index| {
        assert(field.value == .boolean and field.value.boolean);
        if (index > 0) try text.writer.writeAll(" | ");
        try text.writer.print("{s}.{s}", .{ @tagName(record.type), field.name });
    }
    return text.written();
}

fn render_field_value(arena: std.mem.Allocator, field: types.Field) ![]const u8 {
    switch (field.value) {
        .enum_literal => |literal| {
            return std.fmt.allocPrint(arena, "{s}.{s}", .{ field.type.enum_name, literal });
        },
        .record => |record| {
            assert(types.Record.is_flags(record.type));
            return render_flags(arena, record);
        },
        .integer => |text| {
            if (field.type.int >= 64) return render_bigint(arena, text);
            return text;
        },
        .generate_id, .boolean, .reference, .index => {
            return render_expression(arena, field.value);
        },
        .call, .generate_ids => unreachable,
    }
}

fn render_bigint(arena: std.mem.Allocator, text: []const u8) ![]const u8 {
    return std.fmt.allocPrint(arena, "{s}n", .{text});
}
