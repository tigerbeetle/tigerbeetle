fn emit_case(
    printer: *Printer,
    case: ast.Case,
) !void {
    var scope = Scope.init(printer);
    const consumed = try printer.arena().alloc(bool, case.steps.len);
    @memset(consumed, false);
    for (case.steps, 0..) |step, index| {
        if (consumed[index]) continue;
        if (step == .binding and step.binding.value == .index and
            !scope.id_arrays.contains(step.binding.value.index.reference))
        {
            try emit_row_group(&scope, case.steps, index, consumed);
        } else {
            try emit_step(&scope, step);
        }
    }
}

// A Java result batch is a cursor, not a list of rows, so indexed bindings never become locals.
// Each row is reached with `next()`, and its assertions follow it, like in `IntegrationTest`.
fn emit_row_group(
    scope: *Scope,
    steps: []const ast.Step,
    start: usize,
    consumed: []bool,
) !void {
    const printer = scope.printer;
    const origin = steps[start].binding.value.index;
    const batch = try printer.to_case_alloc(.camelCase, origin.reference);

    const Row = struct { name: []const u8, index: u32 };
    var rows: std.ArrayList(Row) = .empty;
    for (steps[start..], start..) |step, index| {
        if (step != .binding or step.binding.value != .index) continue;
        if (!std.mem.eql(u8, step.binding.value.index.reference, origin.reference)) continue;
        if (rows.getLastOrNull()) |last| assert(step.binding.value.index.index > last.index);
        try rows.append(printer.arena(), .{
            .name = step.binding.name,
            .index = step.binding.value.index.index,
        });
        consumed[index] = true;
    }

    try scope.walk(batch);
    var position: u32 = 0;
    for (rows.items) |entry| {
        const row = entry.name;
        while (position <= entry.index) : (position += 1) {
            try printer.print_indented("assertTrue({s}.next());", .{batch});
        }
        try emit_row_captures(printer, steps, row, batch, consumed);
        for (steps, 0..) |step, index| {
            if (step != .assertion) continue;
            var comparison: ast.Assertion.FieldComparison = undefined;
            var greater_than = false;
            switch (step.assertion) {
                .equal_field => |value| comparison = value,
                .greater_than => |value| {
                    comparison = value;
                    greater_than = true;
                },
                else => continue,
            }
            if (comparison.expected == .field_reference) {
                try emit_row_equal_field(printer, steps, .{
                    .comparison = comparison,
                    .row = row,
                    .batch = batch,
                    .consumed = &consumed[index],
                });
                continue;
            }
            if (!std.mem.eql(u8, comparison.actual.reference, row)) continue;
            consumed[index] = true;

            const property = try printer.to_case_alloc(.PascalCase, comparison.actual.field.name);
            const value = try render_typed_value(
                printer,
                comparison.actual.field,
                comparison.expected.expression,
            );
            try printer.write_indent();
            if (greater_than) {
                try printer.print("assertTrue({s}.get{s}() > {s});\n", .{ batch, property, value });
            } else {
                try printer.print("{s}({s}, {s}.get{s}());\n", .{
                    assert_function(comparison.actual.field),
                    value,
                    batch,
                    property,
                });
            }
        }
    }
}

// There is no row local, so a field bound off a row is captured while the cursor is on it.
fn emit_row_captures(
    printer: *Printer,
    steps: []const ast.Step,
    row: []const u8,
    batch: []const u8,
    consumed: []bool,
) !void {
    for (steps, 0..) |step, index| {
        if (step != .binding or step.binding.value != .field_access) continue;
        const access = step.binding.value.field_access;
        if (!std.mem.eql(u8, access.reference, row)) continue;
        consumed[index] = true;
        try printer.print_indented("final var {s} = {s}.get{s}();", .{
            try printer.to_case_alloc(.camelCase, step.binding.name),
            batch,
            try printer.to_case_alloc(.PascalCase, access.field.name),
        });
    }
}

fn emit_row_equal_field(
    printer: *Printer,
    steps: []const ast.Step,
    options: struct {
        comparison: ast.Assertion.FieldComparison,
        row: []const u8,
        batch: []const u8,
        consumed: *bool,
    },
) !void {
    const actual = options.comparison.actual;
    const expected = options.comparison.expected.field_reference;
    const walks_actual = std.mem.eql(u8, actual.reference, options.row);
    const walks_expected = std.mem.eql(u8, expected.reference, options.row);
    if (!walks_actual and !walks_expected) return;

    const assertion = assert_function(actual.field);
    if (walks_actual and walks_expected) {
        options.consumed.* = true;
        try printer.print_indented("{s}({s}.get{s}(), {s}.get{s}());", .{
            assertion,
            options.batch,
            try printer.to_case_alloc(.PascalCase, expected.field.name),
            options.batch,
            try printer.to_case_alloc(.PascalCase, actual.field.name),
        });
        return;
    }

    const here = if (walks_actual) actual else expected;
    const there = if (walks_actual) expected else actual;
    const property = try printer.to_case_alloc(.PascalCase, here.field.name);
    if (walks_before(steps, options.row, there.reference)) {
        try printer.print_indented("final var {s} = {s}.get{s}();", .{
            try capture_name(printer, here),
            options.batch,
            property,
        });
        return;
    }

    options.consumed.* = true;
    const captured = try capture_name(printer, there);
    const walked = try printer.string_alloc("{s}.get{s}()", .{
        options.batch,
        property,
    });
    try printer.print_indented("{s}({s}, {s});", .{
        assertion,
        if (walks_actual) captured else walked,
        if (walks_actual) walked else captured,
    });
}

fn capture_name(printer: *Printer, reference: ast.FieldReference) ![]const u8 {
    return printer.string_alloc("{s}{s}", .{
        try printer.to_case_alloc(.camelCase, reference.reference),
        try printer.to_case_alloc(.PascalCase, reference.field.name),
    });
}

fn walks_before(steps: []const ast.Step, row: []const u8, other: []const u8) bool {
    const first = row_position(steps, row);
    const second = row_position(steps, other);
    if (first.batch != second.batch) return first.batch < second.batch;
    return first.row < second.row;
}

fn row_position(steps: []const ast.Step, row: []const u8) struct { batch: usize, row: usize } {
    for (steps, 0..) |step, index| {
        if (step != .binding or step.binding.value != .index) continue;
        if (!std.mem.eql(u8, step.binding.name, row)) continue;
        const reference = step.binding.value.index.reference;
        for (steps, 0..) |batch_step, batch_index| {
            if (batch_step != .binding or batch_step.binding.value != .index) continue;
            if (std.mem.eql(u8, batch_step.binding.value.index.reference, reference)) {
                return .{ .batch = batch_index, .row = index };
            }
        }
        unreachable;
    }
    unreachable;
}

// Java has no standalone record type, only batches, so a bound record is written out at each use.
const Scope = struct {
    printer: *Printer,
    records: std.StringHashMap(ast.Record),
    id_arrays: std.StringHashMap(void),
    walked: std.StringHashMap(void),

    fn init(printer: *Printer) Scope {
        return .{
            .printer = printer,
            .records = std.StringHashMap(ast.Record).init(printer.arena()),
            .id_arrays = std.StringHashMap(void).init(printer.arena()),
            .walked = std.StringHashMap(void).init(printer.arena()),
        };
    }

    fn walk(scope: *Scope, batch: []const u8) !void {
        const entry = try scope.walked.getOrPut(batch);
        if (!entry.found_existing) return;
        const printer = scope.printer;
        // A batch is a cursor, so a second pass over one has to rewind first.
        try printer.print_indented("{s}.beforeFirst();", .{batch});
    }
};

fn emit_step(scope: *Scope, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(scope, binding),
        .call => |call| try emit_call(scope, call, .{}),
        .assertion => |assertion| try emit_assertion(scope, assertion),
    }
}

fn emit_binding(scope: *Scope, binding: ast.Binding) !void {
    const printer = scope.printer;
    const name = try printer.to_case_alloc(.camelCase, binding.name);
    switch (binding.value) {
        .generate_id => {
            try printer.print_indented("final var {s} = UInt128.id();", .{name});
        },
        .generate_ids => |count| {
            try scope.id_arrays.put(binding.name, {});
            try printer.print_indented("final var {s} = new byte[{d}][];", .{ name, count });
            try printer.print_indented("for (int index = 0; index < {d}; index++) {{", .{count});
            printer.indent();
            try printer.print_indented("if (index % {d} == 0) {{", .{
                ast.ids_between_sleeps,
            });
            printer.indent();
            try printer.write_indented("Thread.sleep(1);");
            printer.dedent();
            try printer.write_indented("}");
            try printer.print_indented("{s}[index] = UInt128.id();", .{name});
            printer.dedent();
            try printer.write_indented("}");
        },
        .index => |index| {
            const reference = try printer.to_case_alloc(.camelCase, index.reference);
            try printer.print_indented("final var {s} = {s}[{d}];", .{
                name, reference, index.index,
            });
        },
        .record => |record| switch (record.type) {
            .U128 => {
                assert(record.fields.len == 1);
                const value = try render_uint128(printer, record.fields[0].value.integer);
                try printer.print_indented("final var {s} = {s};", .{ name, value });
            },
            .Account, .Transfer => {
                try scope.records.put(binding.name, try hoist_record(scope, name, record));
            },
            .AccountBalance,
            .AccountFilter,
            .AccountFilterFlags,
            .AccountFlags,
            .CreateAccountResult,
            .CreateTransferResult,
            .QueryFilter,
            .QueryFilterFlags,
            .TransferFlags,
            => unreachable,
        },
        .call => |call| try emit_call(scope, call, .{ .binding = name }),
        .integer,
        .boolean,
        .enum_literal,
        .reference,
        .field_access,
        .increment,
        .decrement,
        => unreachable,
    }
}

// Puts each generated id into a local and returns the record with the id fields using it.
fn hoist_record(
    scope: *Scope,
    name: []const u8,
    record: ast.Record,
) !ast.Record {
    const printer = scope.printer;
    const fields = try printer.arena().alloc(ast.FieldValue, record.fields.len);
    for (record.fields, 0..) |field, index| {
        if (field.value != .generate_id) {
            fields[index] = field;
            continue;
        }
        const local = try printer.string_alloc("{s}{s}", .{
            name,
            try printer.to_case_alloc(.PascalCase, field.field.name),
        });
        try printer.print_indented("final var {s} = UInt128.id();", .{local});
        fields[index] = .{ .field = field.field, .value = .{ .reference = local } };
    }
    return .{ .type = record.type, .fields = fields };
}

fn emit_call(
    scope: *Scope,
    call: ast.Call,
    options: struct {
        binding: ?[]const u8 = null,
        expect_error: bool = false,
    },
) !void {
    const printer = scope.printer;
    if (call.concurrency > 1) {
        assert(options.binding == null);
        try printer.print_indented("final var threads = new Thread[{d}];", .{call.concurrency});
        try printer.print_indented("final var exceptions = new Exception[{d}];", .{
            call.concurrency,
        });
        try printer.print_indented("for (int index = 0; index < {d}; index++) {{", .{
            call.concurrency,
        });
        printer.indent();
        try printer.write_indented("final var threadIndex = index;");
        try printer.write_indented("threads[index] = new Thread(() -> {");
        printer.indent();
        try printer.write_indented("try {");

        printer.indent();
        var thread_scope = Scope.init(printer);
        try emit_invocation(&thread_scope, call, .{});
        printer.dedent();

        try printer.write_indented("} catch (Exception exception) {");
        printer.indent();
        try printer.write_indented("exceptions[threadIndex] = exception;");
        printer.dedent();
        try printer.write_indented("}");
        printer.dedent();
        try printer.write_indented("});");
        try printer.write_indented("threads[index].start();");
        printer.dedent();
        try printer.write_indented("}");
        try printer.write_indented("for (final var thread : threads) {");
        printer.indent();
        try printer.write_indented("thread.join(Duration.ofSeconds(60).toMillis());");
        try printer.write_indented(
            "assertTrue(\"Worker did not terminate within 60 seconds\", !thread.isAlive());",
        );
        printer.dedent();
        try printer.write_indented("}");
        try printer.write_indented("for (final var exception : exceptions) {");
        printer.indent();
        try printer.write_indented("if (exception != null)");
        printer.indent();
        try printer.write_indented("throw exception;");
        printer.dedent();
        printer.dedent();
        try printer.write_indented("}");
        return;
    }

    try emit_invocation(scope, call, .{
        .binding = options.binding,
        .expect_error = options.expect_error,
    });
}

fn emit_invocation(
    scope: *Scope,
    call: ast.Call,
    options: struct {
        binding: ?[]const u8 = null,
        expect_error: bool = false,
    },
) !void {
    const printer = scope.printer;
    switch (call.name) {
        .close_client => {
            assert(options.binding == null);
            try printer.write_indented("client.close();");
            return;
        },
        .sleep_ms => {
            assert(options.binding == null);
            assert(call.arguments.len == 1);
            try printer.print_indented("Thread.sleep({s});", .{call.arguments[0].integer});
            return;
        },
        else => {},
    }

    // An unbound call uses a fixed local name for its input, so a block lets the name repeat.
    const scoped = options.binding == null;
    if (scoped) {
        try printer.write_indented("{");
        printer.indent();
    }

    // The input goes into a final local, which the `assertThrows` lambda can use.
    const argument = try emit_argument(scope, call, options.binding);

    try printer.write_indent();
    if (options.expect_error) {
        try printer.print("assertThrows(Exception.class, () -> client.{s}({s}));\n", .{
            java_operation_name(call.name),
            argument,
        });
    } else {
        if (options.binding) |binding| try printer.print("final var {s} = ", .{binding});
        try printer.print("client.{s}({s});\n", .{ java_operation_name(call.name), argument });
    }

    if (scoped) {
        printer.dedent();
        try printer.write_indented("}");
    }
}

fn local_name(
    printer: *Printer,
    binding: ?[]const u8,
    suffix: []const u8,
    unbound: []const u8,
) ![]const u8 {
    const name = binding orelse return unbound;
    return printer.string_alloc("{s}{s}", .{ name, suffix });
}

fn emit_argument(
    scope: *Scope,
    call: ast.Call,
    binding: ?[]const u8,
) ![]const u8 {
    const printer = scope.printer;
    switch (call.name) {
        .create_accounts, .create_transfers => {
            const accounts = call.name == .create_accounts;
            const batch_type = if (accounts) "AccountBatch" else "TransferBatch";
            const name = try local_name(
                printer,
                binding,
                "Batch",
                if (accounts) "accountsBatch" else "transfersBatch",
            );
            try printer.print_indented("final var {s} = new {s}({d});", .{
                name,
                batch_type,
                call.arguments.len,
            });
            for (call.arguments) |argument| {
                const record = switch (argument) {
                    .record => |record| record,
                    .reference => |reference| scope.records.get(reference).?,
                    else => unreachable,
                };
                try emit_record_into(printer, record, name);
            }
            return name;
        },
        .lookup_accounts, .lookup_transfers => {
            const name = try local_name(printer, binding, "Batch", "idsBatch");
            try printer.print_indented("final var {s} = new IdBatch({d});", .{
                name, call.arguments.len,
            });
            for (call.arguments) |argument| {
                try printer.print_indented("{s}.add({s});", .{
                    name,
                    try render_id(printer, argument),
                });
            }
            return name;
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const filter = call.arguments[0].record;
            const name = try local_name(printer, binding, "Filter", "filter");
            try printer.print_indented("final var {s} = new {s}();", .{
                name, @tagName(filter.type),
            });
            for (filter.fields) |field| {
                try emit_filter_field(printer, field, name);
            }
            return name;
        },
        .close_client, .sleep_ms => unreachable,
    }
}

fn emit_record_into(printer: *Printer, record: ast.Record, batch: []const u8) !void {
    try printer.print_indented("{s}.add();", .{batch});
    for (record.fields) |field| {
        try emit_setter(
            printer,
            batch,
            try printer.to_case_alloc(.PascalCase, field.field.name),
            try render_typed_value(printer, field.field, field.value),
        );
    }
}

fn emit_filter_field(
    printer: *Printer,
    field: ast.FieldValue,
    name: []const u8,
) !void {
    if (field.value == .record and ast.Record.is_flags(field.value.record.type)) {
        for (field.value.record.fields) |flag| {
            assert(flag.value == .boolean and flag.value.boolean);
            try printer.print_indented("{s}.set{s}(true);", .{
                name,
                try printer.to_case_alloc(.PascalCase, flag.field.name),
            });
        }
        return;
    }
    try emit_setter(
        printer,
        name,
        try printer.to_case_alloc(.PascalCase, field.field.name),
        try render_typed_value(printer, field.field, field.value),
    );
}

fn emit_signature(printer: *Printer, name: []const u8) !void {
    try printer.write_indented(name);
    printer.indent();
    printer.indent();
    try printer.write_indented("throws Exception {");
    printer.dedent();
    printer.dedent();
}

fn emit_setter(
    printer: *Printer,
    target: []const u8,
    property: []const u8,
    value: []const u8,
) !void {
    var operands = std.mem.splitSequence(u8, value, " | ");
    const first = operands.first();
    if (operands.peek() == null) {
        try printer.print_indented("{s}.set{s}({s});", .{ target, property, value });
        return;
    }

    try printer.print_indented("{s}.set{s}({s}", .{ target, property, first });
    printer.indent();
    printer.indent();
    while (operands.next()) |operand| {
        try printer.print_indented("| {s}{s}", .{
            operand,
            if (operands.peek() == null) ");" else "",
        });
    }
    printer.dedent();
    printer.dedent();
}

fn emit_assertion(scope: *Scope, assertion: ast.Assertion) !void {
    const printer = scope.printer;
    switch (assertion) {
        .equal => |equal| {
            const actual = try printer.to_case_alloc(.camelCase, equal.actual);
            try printer.print_indented("assertEquals({d}, {s}.getLength());", .{
                equal.expected.len,
                actual,
            });
            try scope.walk(actual);
            for (equal.expected) |record| {
                try printer.print_indented("assertTrue({s}.next());", .{actual});
                for (record.fields) |field| {
                    try emit_field_equal(printer, field, actual);
                }
            }
        },
        .empty => |actual| {
            try printer.print_indented("assertEquals(0, {s}.getLength());", .{
                try printer.to_case_alloc(.camelCase, actual),
            });
        },
        .ascending => |ids| {
            const name = try printer.to_case_alloc(.camelCase, ids);
