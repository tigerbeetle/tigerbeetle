const std = @import("std");
const assert = std.debug.assert;

const conformance = @import("conformance");

const ast = conformance.ast;
const Arena = conformance.Arena;
const Printer = conformance.Printer;

pub fn main(init: std.process.Init) !void {
    var stdout_buffer: [4096]u8 = undefined;
    var stdout = std.Io.File.stdout().writerStreaming(init.io, &stdout_buffer);
    const stdout_writer = &stdout.interface;
    var memory: [Arena.default_memory_size]u8 = undefined;
    var arena = Arena.init(&memory);
    var printer = Printer.init(&arena, stdout_writer, .{
        .indent_width = 1,
        .indent_char = '\t',
    });

    try emit(&printer);
    try stdout_writer.flush();
}

fn satisfies(requirement: ast.Case.Requirement) bool {
    return switch (requirement) {
        .requires_unbounded_integers => false,
        .requires_fractional_amounts => false,
    };
}

fn emit(printer: *Printer) !void {
    try printer.write(
        \\////////////////////////////////////////////////////////
        \\// This file was auto-generated by go_conformance.zig //
        \\//              Do not manually modify.               //
        \\////////////////////////////////////////////////////////
        \\
        \\package tigerbeetle_go
        \\
        \\import (
        \\
    );
    printer.indent();
    try printer.write_indented("\"errors\"");
    try printer.write_indented("\"sync\"");
    try printer.write_indented("\"testing\"");
    try printer.write_indented("\"time\"");
    try printer.write_empty_line();
    try printer.write_indented("\"github.com/tigerbeetle/tigerbeetle-go/assert\"");
    printer.dedent();
    try printer.write_indented(")");
    try printer.write_empty_line();
    try printer.write_indented("func TestConformance(t *testing.T) {");
    printer.indent();
    try printer.write_indented("port := startServer(t)");
    try printer.write_empty_line();
    try printer.write_indented(
        "test := func(name string, body func(t *testing.T, client Client)) {",
    );
    printer.indent();
    try printer.write_indented("t.Run(name, func(t *testing.T) {");
    printer.indent();
    try printer.write_indented("client := newClient(t, port)");
    try printer.write_indented("defer client.Close()");
    try printer.write_indented("body(t, client)");
    printer.dedent();
    try printer.write_indented("})");
    printer.dedent();
    try printer.write_indented("}");
    for (conformance.sources) |source| {
        defer printer.arena.reset();

        const suite = try conformance.parse(printer.arena.allocator(), source);
        try printer.write_empty_line();
        try printer.print_indented("// Suite: {s}", .{suite.name});
        for (suite.cases) |case| {
            const case_memory = printer.arena.mark();
            defer printer.arena.release(case_memory);

            try printer.write_empty_line();
            if (case.requirement) |requirement| {
                if (!satisfies(requirement)) {
                    try printer.write_omission(case);
                    continue;
                }
            }
            try printer.write_indented("test(");
            printer.indent();
            try printer.print_indented("\"{s}_{s}\",", .{
                suite.name,
                try printer.to_case_alloc(.snake_case, case.description),
            });
            try printer.write_indented("func(t *testing.T, client Client) {");
            printer.indent();
            try emit_case(printer, case);
            printer.dedent();
            try printer.write_indented("},");
            printer.dedent();
            try printer.write_indented(")");
        }
    }
    printer.dedent();
    try printer.write_indented("}");
    try emit_new_client(printer);
    try emit_u128(printer);
}

fn emit_case(printer: *Printer, case: ast.Case) !void {
    var scope = Scope{};
    for (case.steps) |step| try emit_step(printer, &scope, step);
}

// Tracks what is already declared in the generated `test` body, since Go
// rejects both a redeclared `err` and an unused one.
const Scope = struct {
    error_declared: bool = false,

    fn error_assign(scope: *Scope, binds_result: bool) []const u8 {
        defer scope.error_declared = true;
        return if (binds_result or !scope.error_declared) ":=" else "=";
    }
};

fn emit_step(printer: *Printer, scope: *Scope, step: ast.Step) !void {
    switch (step) {
        .binding => |binding| try emit_binding(printer, scope, binding),
        .call => |call| try emit_call(printer, scope, call, .{}),
        .assertion => |assertion| try emit_assertion(printer, scope, assertion),
        .directive => |directive| try emit_directive(printer, directive),
        .create_client => |arguments| try emit_create_client(printer, scope, arguments, .success),
    }
}

fn emit_directive(printer: *Printer, directive: ast.HarnessDirective) !void {
    switch (directive) {
        .sleep_ms => |ms| {
            try printer.print_indented("time.Sleep({d} * time.Millisecond)", .{ms});
        },
        .concurrently => |concurrently| {
            try printer.write_indented("var wg sync.WaitGroup");
            try printer.print_indented("for i := 0; i < {d}; i++ {{", .{concurrently.n});
            printer.indent();
            try printer.write_indented("wg.Add(1)");
            try printer.write_indented("go func() {");
            printer.indent();
            try printer.write_indented("defer wg.Done()");

            var goroutine_scope = Scope{};
            try emit_call(printer, &goroutine_scope, concurrently.call, .{
                .error_action = .t_error,
            });

            printer.dedent();
            try printer.write_indented("}()");
            printer.dedent();
            try printer.write_indented("}");
            try printer.write_indented("wg.Wait()");
        },
    }
}

fn emit_binding(printer: *Printer, scope: *Scope, binding: ast.Binding) !void {
    const name = try printer.to_case_alloc(.GOCamelCase, binding.name);
    switch (binding.value) {
        .generate_id => {
            try printer.print_indented("{s} := ID()", .{name});
        },
        .generate_ids => |count| {
            try printer.print_indented("{s} := make([]Uint128, {d})", .{ name, count });
            try printer.print_indented("for i := range {s} {{", .{name});
            printer.indent();
            try printer.print_indented("if i%{d} == 0 {{", .{ast.ids_between_sleeps});
            printer.indent();
            try printer.write_indented("time.Sleep(time.Millisecond)");
            printer.dedent();
            try printer.write_indented("}");
            try printer.print_indented("{s}[i] = ID()", .{name});
            printer.dedent();
            try printer.write_indented("}");
        },
        .index => |index| {
            const reference = try printer.to_case_alloc(.GOCamelCase, index.reference);
            try printer.print_indented("{s} := {s}[{d}]", .{ name, reference, index.index });
        },
        .field_access => |access| {
            const value = try render_field_access(printer, access);
            try printer.print_indented("{s} := {s}", .{ name, value });
        },
        .call => |call| try emit_call(printer, scope, call, .{ .binding = name }),
        .integer,
        .boolean,
        .enum_literal,
        .record,
        .reference,
        .increment,
        .decrement,
        => unreachable,
    }
}

const ErrorAction = enum { expected, t_error, t_fatal };

fn emit_call(
    printer: *Printer,
    scope: *Scope,
    call: ast.Call,
    options: struct {
        binding: ?[]const u8 = null,
        error_action: ErrorAction = .t_fatal,
        client_error: ?ast.ClientError = null,
    },
) !void {
    switch (call.name) {
        .close_client => {
            assert(options.binding == null);
            try printer.write_indented("client.Close()");
            return;
        },
        else => {},
    }

    try printer.write_indent();
    try printer.print("{s}, err {s} client.{s}(", .{
        options.binding orelse "_",
        scope.error_assign(options.binding != null),
        go_operation_name(call.name),
    });

    switch (call.name) {
        .create_accounts, .create_transfers => {
            const record_type: ast.Record.Type =
                if (call.name == .create_accounts) .Account else .Transfer;
            if (call.arguments.len == 0) {
                // gofmt collapses an empty composite literal onto a single line.
                try printer.print("[]{s}{{}})\n", .{@tagName(record_type)});
            } else {
                try printer.print("[]{s}{{\n", .{@tagName(record_type)});
                printer.indent();
                for (call.arguments) |argument| try emit_record(printer, argument.record);
                printer.dedent();
                try printer.write_indented("})");
            }
        },
        .lookup_accounts, .lookup_transfers => {
            try printer.write("[]Uint128{");
            for (call.arguments, 0..) |argument, index| {
                if (index > 0) try printer.write(", ");
                try printer.write(try render_id(printer, argument));
            }
            try printer.write("})\n");
        },
        .get_account_transfers, .get_account_balances, .query_accounts, .query_transfers => {
            assert(call.arguments.len == 1);
            const filter = call.arguments[0].record;
            if (filter.fields.len == 0) {
                try printer.print("{s}{{}})\n", .{@tagName(filter.type)});
            } else {
                try printer.print("{s}{{\n", .{@tagName(filter.type)});
                printer.indent();
                try emit_record_fields(printer, filter);
                printer.dedent();
                try printer.write_indented("})");
            }
        },
        .close_client => unreachable,
    }

    switch (options.error_action) {
        .expected => try emit_expected_error(printer, options.client_error),
        .t_error => try emit_error_check(printer, .t_error),
        .t_fatal => try emit_error_check(printer, .t_fatal),
    }
}

fn emit_create_client(
    printer: *Printer,
    scope: *Scope,
    arguments: ast.ClientInitArgs,
    outcome: union(enum) { success, failure: ?ast.ClientError },
) !void {
    const cluster_id = try render_uint128(printer, arguments.cluster_id);
    const replica_addresses = switch (arguments.replica_addresses) {
        .server => "port",
        .literal => |text| try printer.string_alloc("\"{s}\"", .{text}),
    };
    switch (outcome) {
        .success => {
            try printer.print_indented("testClient, err {s} NewClient({s}, []string{{{s}}})", .{
                scope.error_assign(true),
                cluster_id,
                replica_addresses,
            });
            try emit_error_check(printer, .t_fatal);
            try printer.write_indented("testClient.Close()");
        },
        .failure => |client_error| {
            try printer.print_indented("_, err {s} NewClient({s}, []string{{{s}}})", .{
                scope.error_assign(false),
                cluster_id,
                replica_addresses,
            });
            try emit_expected_error(printer, client_error);
        },
    }
}

fn emit_expected_error(printer: *Printer, client_error: ?ast.ClientError) !void {
    if (client_error) |expected| {
        try printer.print_indented("assert.True(t, errors.Is(err, {s}))", .{
            go_error_name(expected),
        });
        return;
    }
    try printer.write_indented("if err == nil {");
    printer.indent();
    try printer.write_indented("t.Fatal(\"expected an error\")");
    printer.dedent();
    try printer.write_indented("}");
}

fn go_error_name(client_error: ast.ClientError) []const u8 {
    return switch (client_error) {
        .too_much_data => "ErrTooMuchData",
        .client_closed => "ErrClientClosed",
        .address_invalid => "ErrInvalidAddress",
        .address_limit_exceeded => "ErrAddressLimitExceeded",
        .cluster_id_invalid => unreachable,
    };
}

fn emit_error_check(printer: *Printer, method: enum { t_error, t_fatal }) !void {
    try printer.write_indented("if err != nil {");
    printer.indent();
    try printer.print_indented("t.{s}(err)", .{switch (method) {
        .t_error => "Error",
        .t_fatal => "Fatal",
    }});
    printer.dedent();
    try printer.write_indented("}");
}

fn emit_record(printer: *Printer, record: ast.Record) !void {
    try printer.write_indented("{");
    printer.indent();
    try emit_record_fields(printer, record);
    printer.dedent();
    try printer.write_indented("},");
}

// Pads field names so values line up, which is what gofmt does to a
// multi-line composite literal.
fn emit_record_fields(printer: *Printer, record: ast.Record) !void {
    var name_width: usize = 0;
    for (record.fields) |field| {
        const name = try printer.to_case_alloc(.GOPascalCase, field.field.name);
        name_width = @max(name_width, name.len);
    }
    for (record.fields) |field| {
        const name = try printer.to_case_alloc(.GOPascalCase, field.field.name);
        const value = try render_typed_value(printer, field.field, field.value);
        try printer.write_indent();
        try printer.print("{s}:", .{name});
        try printer.write_padding(name_width - name.len + 1);
        try printer.print("{s},\n", .{value});
    }
}

fn emit_assertion(printer: *Printer, scope: *Scope, assertion: ast.Assertion) !void {
    switch (assertion) {
        .equal => |equal| {
            const actual = try printer.to_case_alloc(.GOCamelCase, equal.actual);
            try printer.print_indented("assert.Len(t, {s}, {d})", .{ actual, equal.expected.len });
            for (equal.expected, 0..) |record, index| {
                for (record.fields) |field| {
                    const value = try render_typed_value(printer, field.field, field.value);
                    try printer.print_indented("assert.Equal(t, {s}, {s}[{d}].{s})", .{
                        value,
                        actual,
                        index,
                        try printer.to_case_alloc(.GOPascalCase, field.field.name),
                    });
                }
            }
        },
        .empty => |actual| {
            const name = try printer.to_case_alloc(.GOCamelCase, actual);
            try printer.print_indented("assert.Len(t, {s}, 0)", .{name});
        },
        .id_ascending => |ids| {
            const name = try printer.to_case_alloc(.GOCamelCase, ids);
            try printer.print_indented("for i := 1; i < len({s}); i++ {{", .{name});
            printer.indent();
            try printer.print_indented("if {s}[i-1].BigInt().Cmp({s}[i].BigInt()) >= 0 {{", .{
                name, name,
            });
            printer.indent();
            try printer.write_indented("t.Fatal(\"ids are not ascending\")");
            printer.dedent();
            try printer.write_indented("}");
            printer.dedent();
            try printer.write_indented("}");
        },
        .equal_field => |comparison| {
            const actual = try render_field_access(printer, comparison.actual);
            const value = switch (comparison.expected) {
                .expression => |expression| switch (expression) {
                    .increment => |arithmetic| try render_arithmetic(printer, arithmetic, "+", ""),
                    .decrement => |arithmetic| try render_arithmetic(printer, arithmetic, "-", ""),
                    else => try render_typed_value(printer, comparison.actual.field, expression),
                },
                .field_reference => |field| try render_field_access(printer, field),
            };
            try printer.print_indented("assert.Equal(t, {s}, {s})", .{ value, actual });
        },
        .greater_than => |comparison| {
            // `assert.Greater` type-asserts both sides to `uint64` rather than converting.
            const bits = comparison.actual.field.type.int;
            if (bits > 64) @panic("assert_greater_than has no Go form for a u128 field");
            const reference = try render_field_access(printer, comparison.actual);
            const actual = if (bits == 64)
                reference
            else
                try printer.string_alloc("uint64({s})", .{reference});
            try printer.print_indented("assert.Greater(t, {s}, uint64({s}))", .{
                actual,
                comparison.expected.expression.integer,
            });
        },
        .fail => |failure| switch (failure.action) {
            .call => |call| try emit_call(printer, scope, call, .{
                .error_action = .expected,
                .client_error = failure.client_error,
            }),
            .create_client => |arguments| try emit_create_client(printer, scope, arguments, .{
                .failure = failure.client_error,
            }),
        },
    }
}

fn render_field_access(
    printer: *Printer,
    reference: ast.FieldReference,
) ![]const u8 {
    return printer.string_alloc("{s}.{s}", .{
        try printer.to_case_alloc(.GOCamelCase, reference.reference),
        try printer.to_case_alloc(.GOPascalCase, reference.field.name),
    });
}

fn render_arithmetic(
    printer: *Printer,
    arithmetic: ast.Expression.Arithmetic,
    operator: []const u8,
    spacing: []const u8,
) ![]const u8 {
    return printer.string_alloc("{s}{s}{s}{s}{d}", .{
        try printer.to_case_alloc(.GOCamelCase, arithmetic.reference),
        spacing,
        operator,
        spacing,
        arithmetic.by,
    });
}

fn render_typed_value(
    printer: *Printer,
    field: ast.Field,
    value: ast.Expression,
) ![]const u8 {
    switch (value) {
        .enum_literal => |literal| {
            const enum_name = field.type.enum_name;
            return printer.string_alloc("{s}{s}", .{
                go_enum_prefix(enum_name),
                try printer.to_case_alloc(.GOPascalCase, literal),
            });
        },
        .record => |flags| {
            assert(ast.Record.is_flags(flags.type));
            var text = std.Io.Writer.Allocating.init(printer.arena.allocator());
            try text.writer.print("{s}{{", .{@tagName(flags.type)});
            for (flags.fields, 0..) |flag, index| {
                assert(flag.value == .boolean and flag.value.boolean);
                if (index > 0) try text.writer.writeAll(", ");
                const name = try printer.to_case_alloc(.GOPascalCase, flag.field.name);
                try text.writer.print("{s}: true", .{name});
            }
            try text.writer.print("}}.ToUint{d}()", .{flags_bits(flags.type)});
            return text.written();
        },
        .integer => |text| {
            const bits = field.type.int;
            if (bits == 128) return render_uint128(printer, text);
            return text;
        },
        .generate_id => return "ID()",
        .reference => |name| return printer.to_case_alloc(.GOCamelCase, name),
        .index => |index| {
            return printer.string_alloc("{s}[{d}]", .{
                try printer.to_case_alloc(.GOCamelCase, index.reference),
                index.index,
            });
        },
        .boolean => |boolean| return if (boolean) "true" else "false",
        .field_access => |access| return render_field_access(printer, access),
        .increment => |arithmetic| return render_arithmetic(printer, arithmetic, "+", " "),
        .decrement => |arithmetic| return render_arithmetic(printer, arithmetic, "-", " "),
        .call, .generate_ids => unreachable,
    }
}

fn render_id(printer: *Printer, expression: ast.Expression) ![]const u8 {
    switch (expression) {
        .generate_id => return "ID()",
        .reference => |name| return printer.to_case_alloc(.GOCamelCase, name),
        .integer => |text| return render_uint128(printer, text),
        else => unreachable,
    }
}

fn render_uint128(printer: *Printer, text: []const u8) ![]const u8 {
    const value = std.fmt.parseInt(u128, text, 10) catch unreachable;
    if (value <= std.math.maxInt(u64)) {
        return printer.string_alloc("ToUint128({s})", .{text});
    }
    return printer.string_alloc("u128(\"{x}\")", .{value});
}

fn go_operation_name(name: ast.Call.Name) []const u8 {
    return switch (name) {
        .create_accounts => "CreateAccounts",
        .create_transfers => "CreateTransfers",
        .lookup_accounts => "LookupAccounts",
        .lookup_transfers => "LookupTransfers",
        .get_account_transfers => "GetAccountTransfers",
        .get_account_balances => "GetAccountBalances",
        .query_accounts => "QueryAccounts",
        .query_transfers => "QueryTransfers",
        .close_client => unreachable,
    };
}

// Go prefixes status names with the event: `CreateAccountStatus.created` is
// `AccountCreated`.
fn go_enum_prefix(enum_name: []const u8) []const u8 {
    if (std.mem.eql(u8, enum_name, "CreateAccountStatus")) return "Account";
    if (std.mem.eql(u8, enum_name, "CreateTransferStatus")) return "Transfer";
    @panic("unmapped enum type");
}

fn flags_bits(flags_type: ast.Record.Type) u16 {
    return switch (flags_type) {
        .AccountFlags, .TransferFlags => 16,
        .AccountFilterFlags, .QueryFilterFlags => 32,
        else => unreachable,
    };
}

fn emit_new_client(printer: *Printer) !void {
    try printer.write_empty_line();
    try printer.write_indented("func newClient(t *testing.T, port string) Client {");
    printer.indent();
    try printer.write_indented(
        "client, err := NewClient(ToUint128(TIGERBEETLE_CLUSTER_ID), []string{port})",
    );
    try emit_error_check(printer, .t_fatal);
    try printer.write_empty_line();
    try printer.write_indented("return client");
    printer.dedent();
    try printer.write_indented("}");
}

fn emit_u128(printer: *Printer) !void {
    try printer.write_empty_line();
    try printer.write_indented("func u128(hex string) Uint128 {");
    printer.indent();
    try printer.write_indented("value, err := HexStringToUint128(hex)");
    try printer.write_indented("if err != nil {");
    printer.indent();
    try printer.write_indented("panic(err)");
    printer.dedent();
    try printer.write_indented("}");
    try printer.write_indented("return value");
    printer.dedent();
    try printer.write_indented("}");
}
